// Zoom MultiStomp effects for the website, from their module folders (contract v3, platform zdl): each a pinned release
// file served from public/zoom-effects/ and installed onto the pedal by the pedal page's link (docs/ZDL_MODULE_CONTRACT.md).
import MACHINE_MODULES from '../catalog/machine-modules.json'
import type { ModwerkModule, ZdlPlatform } from '../catalog/module-contract-v3'
import { displayName } from '../catalog/module-authors'
import { moduleReleasedAt } from '../catalog/module-releases'
import { assetUrl } from '../hosting'

export type ZoomEffect = ModwerkModule & { platform: ZdlPlatform }

// Generated by npm run modules:generate from sdk/zoom/modules/<id>/modwerk.module.json.
export const ZOOM_EFFECTS: ZoomEffect[] = (MACHINE_MODULES.modules as ModwerkModule[]).filter((module): module is ZoomEffect => module.platform.kind === 'zdl')

export const zoomEffectAuthor = (effect: ZoomEffect) => displayName(effect.author.github, effect.author.name)
export const zoomEffectRepository = (effect: ZoomEffect) => effect.source?.repository ?? effect.platform.binary.release.repository
export const zoomEffectReleasedAt = (effect: ZoomEffect) => moduleReleasedAt(effect.machine + '-' + effect.id, effect.version)
/** The vendored file, served by the site itself (the security policy allows no other origin). */
export const zoomEffectUrl = (effect: ZoomEffect) => assetUrl('zoom-effects/' + effect.id + '/' + effect.version + '/' + effect.platform.file)
export const zoomEffectThumbnail = (effect: ZoomEffect) => assetUrl('module-media/' + effect.machine + '-' + effect.id + '/' + effect.version + '/' + effect.media.find(item => item.kind === 'thumbnail')!.path)

/** The effect file, checked against its pin before anything goes to the pedal. */
export async function fetchZoomEffect(effect: ZoomEffect, load: typeof fetch = fetch): Promise<Uint8Array> {
  const response = await load(zoomEffectUrl(effect))
  if (!response.ok) throw new Error(effect.platform.file + ' could not be downloaded (' + response.status + '). Reload the page and try again.')
  const data = new Uint8Array(await response.arrayBuffer())
  const sha256 = Array.from(new Uint8Array(await crypto.subtle.digest('SHA-256', data.slice())), byte => byte.toString(16).padStart(2, '0')).join('')
  if (data.length !== effect.platform.binary.bytes || sha256 !== effect.platform.binary.sha256) throw new Error(effect.platform.file + ' is not the file this page lists. Reload the page and try again.')
  return data
}

export const matchesZoomEffect = (effect: ZoomEffect, query: string) => {
  const term = query.toLowerCase().trim()
  return !term || [effect.name, effect.presentation.summary, effect.presentation.family, zoomEffectAuthor(effect), effect.platform.file].some(value => value.toLowerCase().includes(term))
}
