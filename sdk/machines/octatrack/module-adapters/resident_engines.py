MANAGER = r'''
/* Modwerk resident engines on demand (resident_engines.c): words reserved for placed engines at the top of each
 * core's arena. The FX allocator's capacity stops below them; compaction (dl_arena), dl_move and the journal's
 * holes all read that capacity. Only resident_engines.c changes the reserve, on the UI task under the stable lock. */
static uint16_t engine_reserved[2];
static unsigned engine_arena(unsigned c) { return dl_pool_words[c]>DL_CODE_START ? dl_pool_words[c]-DL_CODE_START : 0u; }
unsigned dl_engine_reserved(unsigned c) { return c<2 ? engine_reserved[c] : 0u; }
/* The arena the FX code has now, for the STATUS page, the box after a pick and the host's ARENA word. */
unsigned modwerk_dsp_arena_now(unsigned c) { return c<2 ? engine_arena(c)-engine_reserved[c] : 0u; }
/* An engine left: never shrinks the arena under the FX code, only gives it words back. */
void dl_engine_release(unsigned c,unsigned reserve) {
    if(c>1 || reserve>=engine_reserved[c]) return;
    engine_reserved[c]=(uint16_t)reserve;
    if(initialized) allocator.capacity[c]=(uint16_t)(engine_arena(c)-reserve);
}
/* Would these Part sets fit, the live code staying where it is? The allocator's own prepare, then cancel. */
static int __attribute__((noinline)) engine_dry_run(const fx_set keep[2]) {
    uint8_t none[16];
    for(unsigned i=0;i<16;++i) none[i]=DL_NONE;
    allocator.keep[0]=keep[0]; allocator.keep[1]=keep[1];
    uint32_t token=auto_serial+1; if(!token) token=0x80000000u;
    auto_serial=token;
    int r=dl_allocator_prepare(&allocator,none,token);
    if(r==DL_ALLOC_OK) dl_allocator_cancel(&allocator,token);
    return r;
}
volatile uint8_t dl_engine_why[2]; /* diagnostics: resident_engines.h */
/* Evacuation (resident engines on demand): live FX code in the region a claim needs moves below it in one transaction
 * of its own (phase ENGINE_EVACUATING, never a Part path's), the way dl_move moves code. Each new copy is uploaded
 * while the old one runs (the receiver reads every chunk back), then each dispatch entry is rebound to its new copy
 * (one BIND, between two frames: the slot's state stays in X and Y and init does not rerun), and only then are the old
 * copies freed and the capacity lowered, in one step, so nothing is placed into the region in between. A refused or
 * unacknowledged step rebinds every entry it touched to its old copy, sent again until acknowledged (the old copies
 * stay held until then), and frees the new copies; that core evacuates nothing more this boot. */
#define ENGINE_EVACUATING 10u
enum { EVAC_UPLOAD=1, EVAC_BIND, EVAC_REVERSE };
static uint8_t evac_core,evac_step,evac_closed[2];
static uint16_t evac_reserve,evac_patience;
static fx_set evac_touched;
volatile uint32_t dl_engine_evacuations,dl_engine_moves,dl_engine_evac_failures; /* diagnostics, never an ABI */
/* Development view: the evacuation's step | its core << 2 | cores closed to it << 4. */
unsigned dl_engine_evacuation(void) { return (phase==ENGINE_EVACUATING ? (unsigned)(evac_step|evac_core<<2) : 0u)|(unsigned)(evac_closed[0]|evac_closed[1]<<1)<<4; }
static unsigned evac_moved(unsigned c,unsigned p) {
    return allocator.live[c][p].present && allocator.target[c][p].present && allocator.target[c][p].offset!=allocator.live[c][p].offset;
}
static void evac_fail(unsigned c) {
    dl_engine_evac_failures=dl_engine_evac_failures+1; evac_closed[c]=1; dl_engine_why[c]=8;
    evac_step=EVAC_REVERSE; cursor=0; evac_patience=0;
}
/* advance() while phase is ENGINE_EVACUATING: one job of the evacuation at a time on its core. */
static void engine_evacuate(void) {
    unsigned c=evac_core;
    if(waiting) {
        int s=dl_job_status(c);
        if(!s) return;
        dl_job_release(c); waiting=0;
        if(s>0) {
            if(evac_step==EVAC_REVERSE) evac_touched=fx_without(evac_touched,cursor);
            else if(evac_step==EVAC_BIND) dl_engine_moves=dl_engine_moves+1;
            ++cursor;
        } else if(evac_step!=EVAC_REVERSE) evac_fail(c); /* a reverse BIND that did not land is sent again */
    }
    for(;;) {
        while(cursor<DL_PACKAGES && !(evac_moved(c,cursor) && (evac_step!=EVAC_REVERSE || fx_in(evac_touched,cursor)))) ++cursor;
        if(cursor<DL_PACKAGES) break;
        cursor=0;
        if(evac_step==EVAC_UPLOAD) { evac_step=EVAC_BIND; continue; }
        if(evac_step==EVAC_BIND) {
            /* Every entry runs its new copy: the old copies go free and the capacity drops below the region together. */
            dl_allocator_ack(&allocator,current,c); dl_allocator_commit(&allocator,current); dl_allocator_retire(&allocator,current);
            if(evac_reserve>engine_reserved[c]) engine_reserved[c]=evac_reserve;
            allocator.capacity[c]=(uint16_t)(engine_arena(c)-engine_reserved[c]);
            dl_engine_evacuations=dl_engine_evacuations+1; ++dl_residency_commits; result=DL_SELECT_READY;
        } else { dl_allocator_cancel(&allocator,current); ++dl_residency_rollbacks; result=DL_SELECT_UNAVAILABLE; }
        evac_step=0; phase=0; counts(); return;
    }
    const struct code *code=&dl_codes[c][cursor];
    unsigned at=DL_CODE_START+(evac_step==EVAC_REVERSE ? allocator.live[c][cursor].offset : allocator.target[c][cursor].offset);
    if(evac_step==EVAC_UPLOAD) {
        struct dl_upload u={code->words,code->relocations,code->count,code->relocation_count,(uint16_t)at};
        waiting=dl_upload_start(c,&u);
    } else {
        if(evac_step==EVAC_BIND) evac_touched=fx_with(evac_touched,cursor); /* touched once sent: its reverse is owed */
        waiting=dl_command_start(c,DL_BIND,cursor,at+code->init,at+code->proc);
    }
    if(waiting) evac_patience=0;
    else if(++evac_patience>600u && evac_step!=EVAC_REVERSE) evac_fail(c); /* the transport stayed busy: give up */
}
/* Where the region's live code would go below `low` on core c, largest first: clear of every live copy (its own
 * included: it runs until its entry is rebound) and of the new copies planned before it; big code (a quarter of that
 * arena or more) from `low` down, the rest first fit from the bottom, as the allocator places them. 1 when all of it
 * has a place: to[p] its new offset, 0xffff for code that stays. */
static int __attribute__((noinline)) engine_plan(unsigned c,unsigned low,uint16_t to[DL_PACKAGES]) {
    for(unsigned p=0;p<DL_PACKAGES;++p) to[p]=0xffffu;
    for(;;) {
        unsigned p=DL_PACKAGES,most=0;
        for(unsigned q=0;q<DL_PACKAGES;++q) {
            const struct dl_placement *l=&allocator.live[c][q];
            if(l->present && to[q]==0xffffu && (unsigned)l->offset+l->words>low && l->words>most) p=q,most=l->words;
        }
        if(p==DL_PACKAGES) return 1;
        const struct code *code=&dl_codes[c][p];
        unsigned align=dl_catalog[p].alignment,big=most*4u>=low,base;
        if(!align || (align&(align-1)) || most>low || !code->words || code->count!=most) return 0;
        base=big ? (low-most)&~(align-1) : 0;
        for(unsigned moved=1;moved;) {
            moved=0;
            if(!big) { base=(base+align-1)&~(align-1); if(base+most>low) return 0; }
            for(unsigned q=0;q<2u*DL_PACKAGES && !moved;++q) {
                const struct dl_placement *l=&allocator.live[c][q%DL_PACKAGES];
                unsigned at=q<DL_PACKAGES ? l->offset : to[q-DL_PACKAGES],end=at+l->words;
                if(!l->present || at==0xffffu || base>=end || base+most<=at) continue;
                if(big) { if(at<most) return 0; base=(at-most)&~(align-1); } else base=end;
                moved=1;
            }
        }
        to[p]=(uint16_t)base;
    }
}
/* The region's code at its planned place (twice: back again). */
static void engine_swap(unsigned c,uint16_t to[DL_PACKAGES]) {
    for(unsigned p=0;p<DL_PACKAGES;++p)
        if(to[p]!=0xffffu) { uint16_t at=allocator.live[c][p].offset; allocator.live[c][p].offset=to[p]; to[p]=at; }
}
/* Room for `reserve` words at the top of core c's arena: 1 yes (taken when commit), 0 not now (the manager is busy, an
 * evacuation runs or waits: ask again), -1 no. Only while the manager is idle. Live code in the region must move
 * below it first (commit 2: start that evacuation now; 1: wait), and the bank's Part union must still fit under it,
 * the region's code at its new place: the firm modules, plus the stock effects if they fit before the claim. So no
 * Part switch ever has to load code because an engine came. */
int dl_engine_claim(unsigned c,unsigned reserve,int commit) {
    if(c>1) return -1;
    if(reserve>engine_arena(c)) { dl_engine_why[c]=5; return -1; }
    if(reserve<=engine_reserved[c]) { dl_engine_why[c]=0; return 1; }
    if(journal_generation || phase || waiting || queued_token || allocator.phase || buffers.open || !dl_residency_enabled ||
       !modwerk_stock_hook_export_idle() || modwerk_saved_set_busy()) { dl_engine_why[c]=phase==ENGINE_EVACUATING ? 6 : 1; return 0; }
    if(!initialized) {
        dl_allocator_init(&allocator,dl_catalog,0,0,MODWERK_DSP_ALLOWANCE0,MODWERK_DSP_ALLOWANCE1);
        dl_buffers_init(&buffers,dl_pmap16);
        stubbed[0]=stubbed[1]=dl_stub_at_boot;
        initialized=1;
    }
    for(unsigned k=0;k<2;++k)
        if(!allocator.capacity[k] && engine_arena(k)>engine_reserved[k]) allocator.capacity[k]=(uint16_t)(engine_arena(k)-engine_reserved[k]);
    unsigned low=engine_arena(c)-reserve,moving=0;
    uint16_t to[DL_PACKAGES];
    if(!engine_plan(c,low,to)) { dl_engine_why[c]=2; return -1; }
    for(unsigned p=0;p<DL_PACKAGES;++p) if(to[p]!=0xffffu) moving=1;
    if(moving && evac_closed[c]) { dl_engine_why[c]=8; return -1; }
    if(moving && commit==1) { dl_engine_why[c]=7; return 0; } /* asked again each tick until it may move: no dry run yet */
    uint8_t now[16];
    fx_set firm[2],named[2],soft[2],played[2],both[2],saved[2]={allocator.keep[0],allocator.keep[1]};
    running(now);
    parts(now,firm,named,soft,played);
    for(unsigned i=0;i<16;++i) {                     /* what runs now counts too */
        unsigned p=now[i],k=(i&7)<4 ? 1:0;
        if(p<DL_PACKAGES && !dl_catalog[p].resident && (dl_catalog[p].slots&(i<8 ? 1u:2u))) firm[k]=fx_with(firm[k],p);
    }
    both[0]=fx_or(firm[0],soft[0]); both[1]=fx_or(firm[1],soft[1]);
    uint16_t before=allocator.capacity[c];
    int r=engine_dry_run(both);
    const fx_set *use=r==DL_ALLOC_OK ? both : firm;
    allocator.capacity[c]=(uint16_t)low;
    engine_swap(c,to);
    r=engine_dry_run(use);
    engine_swap(c,to);
    allocator.capacity[c]=before; allocator.keep[0]=saved[0]; allocator.keep[1]=saved[1];
    if(r!=DL_ALLOC_OK) {
        dl_engine_why[c]=r==DL_ALLOC_MEMORY || r==DL_ALLOC_TRANSITION ? 3 : 4;
        return dl_engine_why[c]==3 ? -1 : 0;
    }
    if(moving) {
        if(!commit) { dl_engine_why[c]=0; return 1; }
        uint32_t token=auto_serial+1; if(!token) token=0x80000000u;
        auto_serial=token;
        bytes(allocator.target,allocator.live,sizeof allocator.target);
        for(unsigned p=0;p<DL_PACKAGES;++p) if(to[p]!=0xffffu) allocator.target[c][p].offset=to[p];
        bytes(allocator.requested,allocator.active,16);
        allocator.token=token; allocator.ready=0; allocator.required=(uint8_t)(1u<<c); allocator.phase=1;
        bytes(desired,allocator.active,16); current=token; result=DL_SELECT_WAIT; automatic=1; cursor=0; waiting=0; cancelling=0;
        evac_core=(uint8_t)c; evac_step=EVAC_UPLOAD; evac_reserve=(uint16_t)reserve; evac_patience=0; evac_touched=(fx_set){{0}};
        phase=ENGINE_EVACUATING; dl_engine_why[c]=6;
        return 0;
    }
    if(commit) { engine_reserved[c]=(uint16_t)reserve; allocator.capacity[c]=(uint16_t)low; }
    dl_engine_why[c]=0;
    return 1;
}
'''


def manager(text):
    """The generated manager.c, after resident_journal.manager and before zero_state.unit."""
    text = _change(text, INIT_BLOCK, INIT_BLOCK, 'manager init')  # the claim repeats exactly this initialization
    text = _change(text, '                allocator.capacity[c]=(uint16_t)(dl_pool_words[c]-DL_CODE_START);',
                   '                allocator.capacity[c]=(uint16_t)(dl_pool_words[c]-DL_CODE_START-engine_reserved[c]);',
                   'manager capacity')
    text = _change(text, 'static uint32_t journal_generation;\n', 'static uint32_t journal_generation;\n'
                   'static uint16_t engine_reserved[2]; /* resident engines on demand: see dl_engine_claim */\n'
                   'static void engine_evacuate(void);  /* ... and its evacuation, phase ENGINE_EVACUATING (10) */\n',
                   'manager storage')
    # The evacuation is a transaction of its own: advance() hands its phase to it, and nothing else starts meanwhile.
    text = _change(text, '    if(!phase) return;\n    if(phase==1) {\n',
                   '    if(!phase) return;\n    if(phase==10) { engine_evacuate(); return; }\n    if(phase==1) {\n', 'manager evacuation')
    body = MANAGER.replace('static uint16_t engine_reserved[2];\n', '', 1)
    return _change(text, 'unsigned dl_arena(unsigned c) { return c<2 ? allocator.capacity[c] : 0; }\n',
                   'unsigned dl_arena(unsigned c) { return c<2 ? allocator.capacity[c] : 0; }\n' + body, 'manager arena')


def transport(text):
    """The generated transfer.c, after resident_driver.transport."""
    return _change(text, '    if(op==10u && (id&~(c ? 5u:7u) || init&~(c ? 5u:7u) || proc)) return 0;',
                   '    if(op==10u && (proc>1u || (!proc && (id&~(c ? 5u:7u) || init&~(c ? 5u:7u))))) return 0;\n'
                   '    /* PLACE (word 7 = 1): one on-demand feature this core carries; offset 0 unplaces, else a table\n'
                   '     * offset inside the arena (the receiver bounds the engine\'s end by its permanent block). */\n'
                   '    if(op==10u && proc==1u && ((id!=1u && id!=2u && id!=4u) || id&~(c ? 5u:7u) ||\n'
                   '       (init && (init<DL_CODE_START || init>=dl_pool_words[c])))) return 0;', 'transport PLACE')


def status(text):
    """status.c: the STATUS page, the MEMORY box and the host's ARENA word read the lowered arena."""
    text = _change(text, 'extern const uint16_t modwerk_dsp_arena[2];\n',
                   'extern const uint16_t modwerk_dsp_arena[2];\nunsigned modwerk_dsp_arena_now(unsigned); /* resident engines on demand */\n',
                   'status declaration')
    for core in (0, 1):
        old = 'modwerk_dsp_arena[%d]' % core
        if text.count(old) != 3:
            raise ValueError('Resident engines seam changed (status arena reads)')
        text = text.replace(old, 'modwerk_dsp_arena_now(%d)' % core)
    return text


