"""The boot stub's sector (docs/OCTATRACK_TWO_SLOT_BASE.md, slots.h), built from stub.s, stub.c and slots.c for
NOR at SLOT_STUB_CODE: the trampoline Elektron's bootloader unpacks to 0x40000400 (a jump to the stub), the mark
bases recognise it by, and the code. Writes stub_body.c, what the base embeds of it: the sector after its 18-byte
header (which flash.c takes from the container it writes) without the 0xff fill. Our own code only: no stock bytes.

    python3 -B build_stub.py --upstream ~/.cache/modwerk-upstream/elekloader --out DIR [--cc m68k-elf-gcc]

check_stub.py runs the result, with the bootloader's own unpacker from your OS file, in an emulator.
"""
import argparse
import re
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.append(str(Path(__file__).resolve().parents[3]))  # sdk/, for firmware_codec
import firmware_codec  # noqa: E402
HERE = Path(__file__).resolve().parent
LINK = '''ENTRY(stub_entry)
SECTIONS
{
  . = %#x;
  .text : { KEEP(*(.text.entry)) *(.text .text.*) *(.rodata .rodata.*) }
  .data : { *(.data .data.* .sdata .sdata.*) }
  .bss : { *(.bss .bss.* .sbss .sbss.* COMMON) }
  /DISCARD/ : { *(.comment) *(.note*) *(.eh_frame*) }
}
'''
# What the stub must end with, checked in its bytes: the bootloader's last CACR plus ICINVA (stub.s), then the jump.
ICINVA = bytes.fromhex('203c0008c100' '4e7b0002')
JUMP = bytes.fromhex('4ef940000400')


def layout():
    """slots.h's numbers, read from it so the two cannot drift."""
    text = (HERE / 'slots.h').read_text()
    value = lambda name: int(re.search(r'#define %s (0x[0-9a-f]+|\d+)u' % name, text).group(1), 0)
    return {name: value(name) for name in ('SLOT_STUB', 'SLOT_STUB_BYTES', 'SLOT_STUB_CODE', 'SECT', 'STUB_MARK', 'STUB_VERSION')}


def fnv(data):
    h = 0x811c9dc5
    for byte in data:
        h = ((h ^ byte) * 0x01000193) & 0xffffffff
    return h


def build(upstream, out, cc='m68k-elf-gcc'):
    firmware_codec.use_elekloader(upstream)
    from firmware_codec import aplib
    n = layout()
    out.mkdir(parents=True, exist_ok=True)
    elf = out / 'stub.elf'
    with tempfile.TemporaryDirectory() as temp:
        script = Path(temp) / 'stub.ld'
        script.write_text(LINK % n['SLOT_STUB_CODE'])
        subprocess.run([cc, '-mcpu=54455', '-Os', '-std=c99', '-ffreestanding', '-fno-builtin', '-nostdlib', '-fno-pic',
                        '-fno-common', '-ffunction-sections', '-Wl,--gc-sections', '-Wall', '-Wextra', '-Werror',
                        '-T', str(script), '-o', str(elf), *(str(HERE / f) for f in ('stub.s', 'stub.c', 'slots.c'))],
                       check=True)
        sizes = subprocess.run([cc.replace('gcc', 'size'), '-A', str(elf)], check=True, capture_output=True, text=True).stdout
        if re.search(r'^\.(data|bss)\s+[1-9]', sizes, re.M):
            raise ValueError('The stub runs from NOR before the OS: it may have no .data or .bss.\n' + sizes)
        raw = Path(temp) / 'stub.bin'
        subprocess.run([cc.replace('gcc', 'objcopy'), '-O', 'binary', '-j', '.text', str(elf), str(raw)], check=True)
        code = raw.read_bytes()
    room = n['SLOT_STUB_BYTES'] - (n['SLOT_STUB_CODE'] - n['SLOT_STUB'])
    if not code or len(code) > room or ICINVA not in code or code.find(JUMP) < code.find(ICINVA):
        raise ValueError('The stub must fit its sector and end with the instruction cache invalidated, then the jump.')
    trampoline = b'\x4e\xf9' + struct.pack('>I', n['SLOT_STUB_CODE'])  # jmp SLOT_STUB_CODE.l
    section = aplib.pack_section(trampoline)
    if len(section) > n['STUB_MARK'] - n['SECT']:
        raise ValueError('The trampoline section runs into the mark.')
    sector = bytearray(b'\xff' * n['SLOT_STUB_BYTES'])
    sector[n['SECT']:n['SECT'] + len(section)] = section
    sector[n['STUB_MARK']:n['STUB_MARK'] + 16] = b'MWSTUB' + struct.pack('>HII', n['STUB_VERSION'], len(code), fnv(code))
    at = n['SLOT_STUB_CODE'] - n['SLOT_STUB']
    sector[at:at + len(code)] = code
    body = bytes(sector[n['SECT']:])
    head = bytes(sector[n['SECT']:at])
    if body != head + code + b'\xff' * (len(body) - len(head) - len(code)):
        raise ValueError('The stub sector is more than its head and its code: flash.c fills the rest with 0xff.')
    rows = lambda data: ',\n'.join('    ' + ','.join('0x%02x' % b for b in data[i:i + 16]) for i in range(0, len(data), 16))
    (out / 'stub_body.c').write_text(
        '/* SPDX-License-Identifier: GPL-3.0-or-later\n * Generated by build_stub.py: the boot stub\'s sector after its header '
        '(stub.s, stub.c, slots.c), without its 0xff fill:\n * the trampoline\'s section and the mark, then the code. */\n'
        '#include <stdint.h>\nconst uint8_t modwerk_stub_head[%d] = {\n%s};\nconst uint32_t modwerk_stub_code_bytes = %d;\n'
        'const uint8_t modwerk_stub_code[%d] = {\n%s};\n' % (len(head), rows(head), len(code), len(code), rows(code)))
    return body, code


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--upstream', default='~/.cache/modwerk-upstream/elekloader')
    parser.add_argument('--out', type=Path, required=True)
    parser.add_argument('--cc', default='m68k-elf-gcc')
    args = parser.parse_args()
    body, code = build(args.upstream, args.out, args.cc)
    print('stub: %d bytes of code, sector body %d bytes, written to %s' % (len(code), len(body), args.out / 'stub_body.c'))


if __name__ == '__main__':
    main()
