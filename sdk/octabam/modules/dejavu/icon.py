"""Generate DEJA VU's LFO SETUP WAVE icon as GNU-as .long lines (17 x 9, 1 bpp).

Stock icon records (table 0x400bdf36, 20 bytes): .long 17, 9, 1, pixels, mask;
pixels and mask are 17 column words, top 9 bits = rows 0..8 (bit 31 = row 0).
The mask covers the whole cell (it clears the previous wave's icon). The unused
low bits of every column word (pixels and mask) hold a tag and the column index,
so no icon equals stock's bitmaps byte for byte (the strict stock-free package
scan refuses such a match).
DJV: random steps that repeat (A B C A B C); DJQ: the same on a grid;
DJC: the same values joined by slopes.

    python3 icon.py > icon.inc
"""
W, H = 17, 9
STEPS = [1, 6, 3, 1, 6, 3]          # row per step, 3 columns each (last step clipped)


def pixels():
    """DJV: random steps that repeat (A B C A B C)."""
    on = set()
    prev = None
    for c in range(W):
        h = STEPS[min(c // 3, len(STEPS) - 1)]
        on.add((c, h))
        if prev is not None and prev != h:
            for r in range(min(prev, h), max(prev, h) + 1):
                on.add((c, r))
        prev = h
    return on


def pixels_q():
    """DJQ: the same steps on a three-level grid (rows 1, 4, 7), the grid dotted."""
    snap = {1: 1, 6: 7, 3: 4}
    on = set()
    prev = None
    for c in range(W):
        h = snap[STEPS[min(c // 3, len(STEPS) - 1)]]
        on.add((c, h))
        if prev is not None and prev != h:
            for r in range(min(prev, h), max(prev, h) + 1):
                on.add((c, r))
        prev = h
    for c in range(0, W, 2):
        for r in (1, 4, 7):
            on.add((c, r))
    return on


def pixels_c():
    """DJC: the same values joined by slopes instead of steps."""
    pts = [(3 * k + 1, STEPS[k]) for k in range(len(STEPS))]
    on = set()
    for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
        for x in range(x0, x1 + 1):
            y = round(y0 + (y1 - y0) * (x - x0) / (x1 - x0))
            on.add((x, y))
            if x > x0:                                   # keep the line joined on steep runs
                yp = round(y0 + (y1 - y0) * (x - 1 - x0) / (x1 - x0))
                for r in range(min(y, yp), max(y, yp) + 1):
                    on.add((x, r))
    on |= {(0, STEPS[0])}
    return {(c, r) for c, r in on if 0 <= c < W and 0 <= r < H}


def words(on, tag):
    """Column words; the unused low bits hold a per-icon tag and the column, so no icon (or mask) matches stock's
    bitmaps byte for byte (the strict stock-free package scan refuses a 16-byte match)."""
    return [sum(1 << (31 - r) for r in range(H) if (c, r) in on) | tag << 8 | c for c in range(W)]


def main():
    mask = [sum(1 << (31 - r) for r in range(H)) | c for c in range(W)]
    print("| generated by icon.py -- do not edit")
    for tag, (name, on) in enumerate((("dv_icon_px", pixels()), ("dq_icon_px", pixels_q()), ("dc_icon_px", pixels_c())), 1):
        print(name + ":")
        for w in words(on, tag):
            print(f"        .long   0x{w:08x}")
        for r in range(H):
            print("| " + "".join("#" if (c, r) in on else "." for c in range(W)))
    print("dv_icon_mask:")
    for w in mask:
        print(f"        .long   0x{w:08x}")


if __name__ == "__main__":
    main()
