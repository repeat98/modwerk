#!/usr/bin/env python3
"""Rebuild dejavu_core.s (the unit Linked consumes) from dejavu.c + hooks.s + icon.py, or --check.

The builder takes GNU-as units; the algorithm stays in C (host-testable), its
compiler output is checked in so builds need no C step (same as Euclid).
"""
import pathlib
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
FLAGS = ['-mcpu=5475', '-msoft-float', '-O2', '-ffreestanding', '-fno-builtin',
         '-fno-common', '-fno-jump-tables', '-fno-asynchronous-unwind-tables',
         '-fno-ident', '-fomit-frame-pointer']


def generate():
    with tempfile.TemporaryDirectory() as td:
        asm = pathlib.Path(td) / 'dejavu.s'
        subprocess.run(['m68k-elf-gcc', *FLAGS, '-S', str(HERE / 'dejavu.c'), '-o', str(asm)], check=True)
        icon = subprocess.run([sys.executable, str(HERE / 'icon.py')], check=True,
                              capture_output=True, text=True).stdout
        return ('| Generated by generate.py from dejavu.c, hooks.s and icon.py; edit those.\n'
                + asm.read_text() + '\n' + (HERE / 'hooks.s').read_text() + '\n'
                + '        .text\n        .balign 4\n' + icon)


if __name__ == '__main__':
    source = generate()
    dest = HERE / 'dejavu_core.s'
    if '--check' in sys.argv:
        if not dest.exists() or source != dest.read_text():
            sys.exit('dejavu_core.s is stale: run generate.py')
        print('dejavu_core.s matches dejavu.c, hooks.s and icon.py')
    else:
        dest.write_text(source)
        print('wrote', dest)
