#!/usr/bin/env python3
"""Rebuild amiga_core.s (the unit manifest.py links) from amiga.c, or --check. As Butter Fingers' generate.py."""
import pathlib
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
# The draft is staged under sdk/octabam/modules/ for builds: find sdk/ from either place.
SDK = next(p for p in HERE.parents if (p / 'machines/octatrack/include/modwerk_events.h').exists())
FLAGS = ['-mcpu=5475', '-msoft-float', '-O2', '-ffreestanding', '-fno-builtin',
         '-fno-common', '-fno-jump-tables', '-fno-asynchronous-unwind-tables',
         '-fno-ident', '-fomit-frame-pointer', '-I', str(SDK / 'machines/octatrack/include')]


def generate():
    with tempfile.TemporaryDirectory() as td:
        asm = pathlib.Path(td) / 'amiga.s'
        # A relative source name: the compiler writes it into the assembly's line markers, and the check must pass in any checkout.
        subprocess.run(['m68k-elf-gcc', *FLAGS, '-S', 'amiga.c', '-o', str(asm)], check=True, cwd=HERE)
        return '| Generated by generate.py from amiga.c; edit that.\n' + asm.read_text()


if __name__ == '__main__':
    source = generate()
    dest = HERE / 'amiga_core.s'
    if '--check' in sys.argv:
        if not dest.exists() or source != dest.read_text():
            sys.exit('amiga_core.s is stale: run generate.py')
        print('amiga_core.s matches amiga.c')
    else:
        dest.write_text(source)
        print('wrote', dest)
