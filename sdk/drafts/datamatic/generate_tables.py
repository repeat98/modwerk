"""DATAMATIC: writes tables.c, the first 2048 bits of each built-in data stream (python3 -B generate_tables.py).

Mathematical constants and sequences only, computed here with integers: the fractional binary digits of pi, e, the
golden ratio and the square root of two, the Fibonacci word, the primes (bit n set when n is prime) and the
Thue-Morse sequence. MSB first: bit k of a stream is bit 7 - k % 8 of byte k / 8.
"""
from pathlib import Path

BITS = 2048
GUARD = 64


def frac_bits(scaled, one):
    """The first BITS fractional bits of scaled / one (scaled an integer numerator)."""
    frac = scaled % one
    out = []
    for _ in range(BITS):
        frac *= 2
        out.append(1 if frac >= one else 0)
        frac %= one
    return out


def pi_scaled(prec):
    """pi * 2**prec by Machin's formula, with guard bits."""
    def arctan_inv(x):
        one = 1 << (prec + GUARD)
        total, term, n, sign = 0, one // x, 1, 1
        x2 = x * x
        while term:
            total += sign * (term // n)
            term //= x2
            n += 2
            sign = -sign
        return total
    return (16 * arctan_inv(5) - 4 * arctan_inv(239)) >> GUARD


def e_scaled(prec):
    one = 1 << (prec + GUARD)
    total, term, n = 0, one, 0
    while term:
        total += term
        n += 1
        term //= n
    return total >> GUARD


def isqrt(n):
    x = 1 << ((n.bit_length() + 1) // 2)
    while True:
        y = (x + n // x) // 2
        if y >= x:
            return x
        x = y


def streams():
    prec = BITS + 32
    one = 1 << prec
    sqrt5 = isqrt(5 << (2 * prec))
    s = {
        'pi': frac_bits(pi_scaled(prec), one),
        'e': frac_bits(e_scaled(prec), one),
        'phi': frac_bits((one + sqrt5) // 2, one),
        'sqrt2': frac_bits(isqrt(2 << (2 * prec)), one),
    }
    # the Fibonacci word 0100101001001...: S(n) = S(n-1) S(n-2), S(0) = 0, S(1) = 01
    a, b = '0', '01'
    while len(b) < BITS:
        a, b = b, b + a
    s['fibonacci'] = [int(c) for c in b[:BITS]]
    sieve = [False, False] + [True] * (BITS - 2)
    for i in range(2, int(BITS ** 0.5) + 1):
        if sieve[i]:
            for j in range(i * i, BITS, i):
                sieve[j] = False
    s['primes'] = [int(v) for v in sieve]
    s['thue_morse'] = [bin(n).count('1') & 1 for n in range(BITS)]
    return s


def main():
    s = streams()
    assert s['pi'][:8] == [0, 0, 1, 0, 0, 1, 0, 0]          # 0.14159... = 0.001001000011111101101...
    assert s['e'][:8] == [1, 0, 1, 1, 0, 1, 1, 1]           # 0.71828... = 0.1011011111100001...
    assert s['phi'][:8] == [1, 0, 0, 1, 1, 1, 1, 0]         # 0.61803... = 0.1001111000110111...
    assert s['sqrt2'][:8] == [0, 1, 1, 0, 1, 0, 1, 0]       # 0.41421... = 0.0110101000001001...
    lines = ['/* SPDX-License-Identifier: GPL-3.0-or-later',
             ' * Generated by generate_tables.py: do not edit. The first 2048 bits of each built-in stream, MSB first. */',
             '#include "engine.h"', '']
    names = ['pi', 'e', 'phi', 'sqrt2', 'fibonacci', 'primes', 'thue_morse']
    lines.append('const uint8_t dm_tables[%d][%d] = {' % (len(names), BITS // 8))
    for name in names:
        bits = s[name]
        data = [sum(bits[8 * k + j] << (7 - j) for j in range(8)) for k in range(BITS // 8)]
        lines.append('    /* %s */ {' % name)
        for row in range(0, len(data), 16):
            lines.append('        ' + ', '.join('0x%02x' % v for v in data[row:row + 16]) + ',')
        lines.append('    },')
    lines.append('};')
    out = Path(__file__).resolve().parent / 'tables.c'
    out.write_text('\n'.join(lines) + '\n')
    print('wrote', out)


if __name__ == '__main__':
    main()
