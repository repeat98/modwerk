#!/usr/bin/env python3
"""Rebuild butter_fingers_core.s (the unit manifest.py links) from butter_fingers.c, or --check.

The builder takes GNU-as units; the logic stays in C (host-tested by verify.py)
and its compiler output is checked in, so builds need no C step (as Deja Vu).
"""
import pathlib
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
FLAGS = ['-mcpu=5475', '-msoft-float', '-O2', '-ffreestanding', '-fno-builtin',
         '-fno-common', '-fno-jump-tables', '-fno-asynchronous-unwind-tables',
         '-fno-ident', '-fomit-frame-pointer']


def generate():
    with tempfile.TemporaryDirectory() as td:
        asm = pathlib.Path(td) / 'butter_fingers.s'
        subprocess.run(['m68k-elf-gcc', *FLAGS, '-S', str(HERE / 'butter_fingers.c'), '-o', str(asm)], check=True)
        return '| Generated by generate.py from butter_fingers.c; edit that.\n' + asm.read_text()


if __name__ == '__main__':
    source = generate()
    dest = HERE / 'butter_fingers_core.s'
    if '--check' in sys.argv:
        if not dest.exists() or source != dest.read_text():
            sys.exit('butter_fingers_core.s is stale: run generate.py')
        print('butter_fingers_core.s matches butter_fingers.c')
    else:
        dest.write_text(source)
        print('wrote', dest)
