"""Independent digest oracle for the original proposed menu-record fixture."""
import argparse
import hashlib
from pathlib import Path
import struct

ROOT=Path(__file__).resolve().parent

def generated():
    image=bytearray(112)
    image[8:12]=bytes.fromhex('702a4e75')  # Authored return-42 callback, not stock.
    struct.pack_into('>6I',image,32,1,64,51,73,8,0)
    image[56:65]=b'BEAT GRID'
    header=struct.pack('>4sHH6I',b'MWRM',10,0,112,16,0,4,0,9010).ljust(80,b'\0')
    body=struct.pack('>4I',*([0xffffffff]*4))+image
    package=hashlib.sha256(header+body).digest()
    controller=hashlib.sha256(hashlib.sha256(header).digest()+hashlib.sha256(body).digest()).digest()
    text='/* SPDX-License-Identifier: MIT */\n/* Generated by test_menu_package_vectors.py; original fixture hashes only. */\n#ifndef BS_MENU_PACKAGE_VECTORS_H\n#define BS_MENU_PACKAGE_VECTORS_H\n#include <stdint.h>\n'
    for name,digest in (('package',package),('controller',controller)):
        text+='static const uint8_t bs_menu_expected_'+name+'[32] = {'+','.join(f'0x{x:02x}' for x in digest)+'};\n'
    return text+'#endif\n'

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--write',action='store_true');a=p.parse_args()
    path=ROOT/'menu_package_vectors.h';expected=generated()
    if a.write:path.write_text(expected)
    if not path.exists() or path.read_text()!=expected:p.error('Menu fixture digests differ; regenerate with --write.')
    print('PASS: original menu fixture package/controller digests match independent hashlib vectors')

if __name__=='__main__':main()
