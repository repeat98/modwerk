"""Independent hashlib oracle for the authored ABI 10 owner-test packages.

Only expected digests are emitted; no stock bytes, firmware or package image.
"""
import argparse
import hashlib
from pathlib import Path
import struct
ROOT=Path(__file__).resolve().parent
CASES=((9002,32,0x41),(9003,32,0x42),(9002,64,0x43),(9002,64,0x44))
def generated():
    packages=[];controllers=[]
    for module,size,pattern in CASES:
        data=bytearray(80+16+size)
        struct.pack_into('>4sHH6I',data,0,b'MWRM',10,0,size,16,0,4,0,module)
        struct.pack_into('>4I',data,80,*([0xffffffff]*4))
        data[96:]=bytes([pattern])*size
        packages.append(hashlib.sha256(data).digest())
        # No DSP fields are present in these authored headers, so the controller
        # identity is SHA256(SHA256(header) || SHA256(hooks + image)).
        controllers.append(hashlib.sha256(hashlib.sha256(data[:80]).digest()+hashlib.sha256(data[80:]).digest()).digest())
    text='/* SPDX-License-Identifier: MIT */\n/* Generated by test_owner_package_vectors.py; authored fixture digests only. */\n#ifndef BS_OWNER_PACKAGE_VECTORS_H\n#define BS_OWNER_PACKAGE_VECTORS_H\n#include <stdint.h>\n'
    for name,rows in (('bs_expected_packages',packages),('bs_expected_controllers',controllers)):
        text+='static const uint8_t '+name+'[4][32] = {\n'
        for row in rows:text+='    {'+','.join(f'0x{v:02x}' for v in row)+'},\n'
        text+='};\n'
    return text+'#endif\n'
def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--write',action='store_true');a=p.parse_args()
    path=ROOT/'owner_package_vectors.h';expected=generated()
    if a.write:path.write_text(expected)
    if not path.exists() or path.read_text()!=expected:p.error('Authored package/controller digest vectors differ; regenerate with --write.')
    print('PASS: four authored ABI 10 packages and controller identities match independent hashlib vectors')
if __name__=='__main__':main()
