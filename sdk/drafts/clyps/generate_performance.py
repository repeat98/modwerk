"""Generate the Octabam GNU-as unit from the performance C and the private SDK marker."""
import argparse
from pathlib import Path
import subprocess
import sys
import tempfile

here = Path(__file__).resolve().parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('sdk', type=Path, help='Contributor SDK at 5c32cbacd')
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
sdk = args.sdk.resolve()
sys.path[:0] = [str(sdk/'runtime/loader'),str(sdk/'runtime')]
import build
import m68k_codegen

with tempfile.TemporaryDirectory() as tmp:
    work = Path(tmp)
    marker = work/'marker.c'
    marker.write_text('#include "modwerk_events.h"\nconst struct modwerk_modal_input clyps_modal = { MODWERK_MODAL_INPUT_ABI };\n')
    flags = [*build.CFLAGS,*m68k_codegen.FLAGS,'-DCLYPS_PERFORMANCE','-I',sdk/'machines/octatrack/include']
    parts = ['| Generated by generate_performance.py from the C sources.\n']
    for src in (here/'live_module.c', marker):
        asm = work/(src.stem+'.s')
        subprocess.run(['m68k-elf-gcc',*flags,'-S',src.name,'-o',asm],cwd=src.parent,check=True)
        parts.append(asm.read_text())
    data = ''.join(parts)
    dest = here/'performance_core.s'
    if args.check:
        if data != dest.read_text(): sys.exit('Stale performance_core.s')
    else:
        dest.write_text(data)
