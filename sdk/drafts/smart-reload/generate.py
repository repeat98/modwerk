#!/usr/bin/env python3
"""Rebuild smart_reload_core.s (the unit manifest.py links) from smart_reload.c, or --check.

The builder takes GNU-as units; the logic stays in C (host-tested by verify.py) and its compiler output is checked
in, so builds need no C step (as Songbook and Butter Fingers). The flags are Butter Fingers' plus the shared ColdFire guard
(sdk/runtime/m68k_codegen.py) and no loop-to-memcpy rewrite: there is no C library.
"""
import pathlib
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[2] / 'sdk' / 'runtime'))
import m68k_codegen  # noqa: E402

FLAGS = ['-mcpu=5475', '-msoft-float', '-O2', '-ffreestanding', '-fno-builtin', '-fno-common', '-fno-jump-tables',
         '-fno-asynchronous-unwind-tables', '-fno-ident', '-fomit-frame-pointer', '-fno-tree-loop-distribute-patterns',
         *m68k_codegen.FLAGS]


if __import__('os').environ.get('SR_DEBUG'):          # a debug build: the row taken shown on screen after a reload
    FLAGS.append('-DSR_DEBUG')


def generate():
    with tempfile.TemporaryDirectory() as td:
        asm = pathlib.Path(td) / 'smart_reload.s'
        subprocess.run(['m68k-elf-gcc', *FLAGS, '-S', str(HERE / 'smart_reload.c'), '-o', str(asm)], check=True)
        text = asm.read_text()
        obj = pathlib.Path(td) / 'smart_reload.o'
        subprocess.run(['m68k-elf-gcc', *FLAGS, '-c', str(HERE / 'smart_reload.c'), '-o', str(obj)], check=True)
        undefined = subprocess.run(['m68k-elf-nm', '-u', str(obj)], check=True, capture_output=True, text=True).stdout.split()
        if undefined:
            sys.exit('smart_reload.c needs symbols nothing provides: ' + ' '.join(undefined[1::2] or undefined))
        subprocess.run([sys.executable, '-B', str(HERE.parents[2] / 'sdk' / 'runtime' / 'm68k_codegen.py'), str(obj)], check=True)
        return '| Generated by generate.py from smart_reload.c; edit that.\n' + text


if __name__ == '__main__':
    source = generate()
    dest = HERE / 'smart_reload_core.s'
    if '--check' in sys.argv:
        if not dest.exists() or source != dest.read_text():
            sys.exit('smart_reload_core.s is stale: run generate.py')
        print('smart_reload_core.s matches smart_reload.c')
    else:
        dest.write_text(source)
        print('wrote', dest)
