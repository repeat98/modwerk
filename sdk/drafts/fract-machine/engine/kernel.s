        .even
        .global og_join_span
og_join_span:
        SEAM_PROLOGUE
        SEAM_ENTRY 0

        .even
        .global og_join_span_reverse
og_join_span_reverse:
        SEAM_PROLOGUE
        SEAM_ENTRY 1

| A segment from the phase in d5: p, the table entries, its frames, then
| the loop in a6. At exactly `half` the window is the peak for one frame.
.Lseam_span_seg:
        move.l 12(%a5),%d1              | step
        cmp.l 24(%a5),%d5               | half
        bcc.s .Lseam_span_falling
        move.l %d5,%d2                  | rising: p = phase
        movea.l %d1,%a3
        move.l #0x00ffffff,%d0
        and.l %d2,%d0
        neg.l %d0
        add.l %d1,%d0
        addi.l #0x00ffffff,%d0
        divu.l %d1,%d0                  | k = ceil((2^24 - p mod 2^24) / step)
        movea.l 16(%a5),%a4             | the attack half
        move.l %d2,%d3
        moveq #23,%d4
        lsr.l %d4,%d3
        bclr #0,%d3                     | 2i
.Lseam_span_entry:
        adda.l %d3,%a4
        mvz.w (%a4)+,%d3                | left = t[i]
        mvz.w (%a4),%d4
        sub.l %d3,%d4                   | delta = t[i+1] - t[i]
.Lseam_span_go:
        move.l %d0,%d1
        lsl.l #3,%d1
        lea (%a1,%d1.l),%a2             | the segment's end
        cmpa.l 44(%sp),%a2
        bls.s 1f
        movea.l 44(%sp),%a2             | the span's last segment
1:      mulu.l 12(%a5),%d0
        add.l %d0,%d5                   | the next segment's phase
        swap %d3
        movea.l %d3,%a4                 | left << 16
        jmp (%a6)
.Lseam_span_falling:
        beq.s .Lseam_span_top
        move.l #0x80000000,%d2
        sub.l %d5,%d2                   | p = 2^31 - phase
        move.l %d1,%d0
        neg.l %d0
        movea.l %d0,%a3
        move.l #0x00ffffff,%d0
        and.l %d2,%d0
        divu.l %d1,%d0
        addq.l #1,%d0                   | k = (p mod 2^24) / step + 1
        movea.l 20(%a5),%a4             | the release half
        move.l %d2,%d3
        moveq #23,%d4
        lsr.l %d4,%d3
        bclr #0,%d3                     | 2i
        bra.s .Lseam_span_entry
.Lseam_span_top:
        move.l %d5,%d3
        moveq #23,%d4
        lsr.l %d4,%d3                   | 2 * (half >> 24): half is a whole segment
        movea.l 16(%a5),%a4
        mvz.w (%a4,%d3.l),%d3           | left = attack[half >> 24], the peak
        moveq #0,%d4                    | delta 0
        moveq #1,%d0                    | one frame
        movea.l %d1,%a3
        move.l %d5,%d2                  | p: any, delta is 0
        bra.s .Lseam_span_go
.Lseam_span_next:
        cmpa.l 44(%sp),%a1
        bne.w .Lseam_span_seg
        movem.l (%sp),%d2-%d7/%a2-%a6
        lea 56(%sp),%sp
        rts
