| og_mix_span (kernel.h): one head's span, mixed into the accumulator.
| scripts/build.py appends this file to the grain unit; host builds run the
| C twin in pitch.c, and the QEMU profiler's kernel-twin rows hold the two
| equal bit for bit (scripts/coldfire_profile.py).
|
| A span crosses the window's 1/128 segments; the code at .Lspan_seg splits
| it there, once a segment: the mirrored phase p (the phase below `half`,
| else 2^31 minus it), the segment's table entry `left` and the next one
| minus it, `delta` (0 at the release's top), and its frames, k =
| ceil((next boundary - p) / step) rising, (p mod 2^24) / step + 1 falling,
| 1 at the switch itself, where the window is the peak. Then the frame loop for the span's format, PAN scaling and
| add/store runs those k frames and returns there.
|
| Each frame: env = left + ((delta * (uint16)(p >> 8)) >> 16), the PCM (the
| upper two bytes of a 24-bit sample), 0.9.6's in-place PAN scaling
| (pcm * gain) >> 8 when a gain is not 256, then pcm * env added to (or, on
| `first`, stored in) two accumulator words. env is at most 21,845 and a
| PAN-scaled sample an int16, so every product is one muls.w; env is formed
| as (delta * u + (left << 16)) >> 16, which is exact because |delta * u|
| stays below 2^29 (the steepest SHPE row) and the sum below 2^31.
|
| One straight-line loop per format, PAN scaling and add/store, generated by
| the macros below (paired at low step, scalar otherwise), chosen once a span.
| The loops read the sample arena with as few accesses as the layout
| allows: PCM16 stereo one longword a frame, PCM16 mono one word, PCM24
| stereo one word (the left sample's upper bytes) and one longword (the
| right's) a frame. PCM24 stereo frames are 6 bytes in 6,144-byte pages, so
| they start at even addresses and that longword is word-aligned; at a frame
| on 0 mod 4 it is not longword-aligned, which ColdFire allows and splits.
| PCM24 mono frames are 3 bytes and start at odd addresses half the time, so
| their samples stay two byte reads.
|
| og_mix_span_reverse (REV) mixes the same span reading its frames
| downwards, from the first frame: the loops below with `dir` 1, which read
| by predecrement (PCM24 mono: the frame, then three bytes down), so a frame
| costs what it costs forwards. PCM24 stereo reads the right sample's
| longword first, then the left's word, and adds left then right as
| forwards.
|
| Registers in the loop: a0 the PCM, a1 the accumulator, a2 the segment's
| end in it, a3 the step (negative falling), a4 left << 16, a5 the span, a6
| the loop; d0 env, d1/d3 samples, d2 the phase p, d4 delta, d5 the next
| segment's phase, d6 gain_l, d7 gain_r. 44(sp) holds the span's end.
| d2-d7/a2-a6 are saved and restored. Only addressing forms make
| image-check admits: no scale-8, word-index or memory-indirect operands. No
| EMAC.

| The envelope of p in the low word of d0, then p += step.
        .macro ENV
        move.l %d2,%d0
        lsr.l #8,%d0
        mulu.w %d4,%d0
        add.l %a4,%d0
        swap %d0
        add.l %a3,%d2
        .endm

| One channel of one frame: the sample in the low word of \reg.
        .macro PUT reg, gain, scaled, op
        .if \scaled
        muls.w \gain,\reg
        asr.l #8,\reg
        .endif
        muls.w %d0,\reg
        \op\().l \reg,(%a1)+
        .endm

| Paired frames for format \fmt (kernel.h; the pairs run as 3), upwards
| or, with \dir 1, downwards: a0 first moves past the first frame for the
| predecrementing reads. Chosen once a span: a6 takes the loop, then the
| first segment; each segment's frames end at a2.
| One frame, shared by the odd prefix and paired body.
        .macro FRAME fmt, scaled, op, dir=0
        ENV
        .if \fmt == 0
        .if \dir
        move.b (%a0),%d1
        lsl.l #8,%d1
        move.b 1(%a0),%d1
        subq.l #3,%a0
        .else
        move.b (%a0)+,%d1
        lsl.l #8,%d1
        move.b (%a0)+,%d1
        addq.l #1,%a0
        .endif
        .endif
        .if \fmt == 1
        .if \dir
        move.l -(%a0),%d3
        lsr.l #8,%d3
        move.w -(%a0),%d1
        PUT %d1,%d6,\scaled,\op
        PUT %d3,%d7,\scaled,\op
        .else
        move.w (%a0)+,%d1
        PUT %d1,%d6,\scaled,\op
        move.l (%a0)+,%d1
        lsr.l #8,%d1
        PUT %d1,%d7,\scaled,\op
        .endif
        .endif
        .if \fmt == 2
        .if \dir
        move.w -(%a0),%d1
        .else
        move.w (%a0)+,%d1
        .endif
        .endif
        .if \fmt == 3
        .if \dir
        move.l -(%a0),%d1
        .else
        move.l (%a0)+,%d1
        .endif
        move.l %d1,%d3
        swap %d1
        PUT %d1,%d6,\scaled,\op
        PUT %d3,%d7,\scaled,\op
        .endif
        .if (\fmt & 1) == 0
        .if \scaled
        move.l %d1,%d3
        PUT %d1,%d6,1,\op
        PUT %d3,%d7,1,\op
        .else
        muls.w %d0,%d1
        \op\().l %d1,(%a1)+
        \op\().l %d1,(%a1)+
        .endif
        .endif
        .endm

        .macro LOOP fmt, scaled, op, dir=0
        .if \dir && \fmt == 1
        addq.l #6,%a0
        .endif
        .if \dir && \fmt == 2
        addq.l #2,%a0
        .endif
        .if \dir && \fmt == 3
        addq.l #4,%a0
        .endif
        move.l 12(%a5),%d0
        cmpi.l #0x00020000,%d0
        bhi.w 3f
        lea 1f(%pc),%a6
        bra.w .Lspan_seg
1:      move.l %a2,%d0
        sub.l %a1,%d0
        btst #3,%d0
        beq.w 2f
        FRAME \fmt,\scaled,\op,\dir
        cmpa.l %a2,%a1
        beq.w .Lspan_next
2:      FRAME \fmt,\scaled,\op,\dir
        FRAME \fmt,\scaled,\op,\dir
        cmpa.l %a2,%a1
        bne.w 2b
        bra.w .Lspan_next
3:      lea 4f(%pc),%a6
        bra.w .Lspan_seg
4:      FRAME \fmt,\scaled,\op,\dir
        cmpa.l %a2,%a1
        bne.s 4b
        bra.w .Lspan_next
        .endm

| The four formats for one PAN scaling and add/store; the format is in d0.
        .macro BANK scaled, op, dir=0
        subq.l #2,%d0
        bcs.w .Lpcm24\@
        beq.w .Lmono16\@
        LOOP 3,\scaled,\op,\dir
.Lmono16\@:
        LOOP 2,\scaled,\op,\dir
.Lpcm24\@:
        addq.l #1,%d0
        beq.w .Lstereo24\@
        LOOP 0,\scaled,\op,\dir
.Lstereo24\@:
        LOOP 1,\scaled,\op,\dir
        .endm

| The span into registers (above), its end on the stack; the format is
| left in d0.
        .macro PROLOGUE
        lea -48(%sp),%sp
        movem.l %d2-%d7/%a2-%a6,(%sp)
        movea.l 52(%sp),%a5
        movea.l (%a5),%a0
        movea.l 4(%a5),%a1
        move.l 8(%a5),%d5
        mvz.w 32(%a5),%d0
        lsl.l #3,%d0
        lea (%a1,%d0.l),%a2
        move.l %a2,44(%sp)
        move.l 28(%a5),%d7
        move.l %d7,%d6
        swap %d6
        mvz.b 34(%a5),%d0
        .endm

| The loops for one direction: store or add, PAN scaled or not.
        .macro ENTRY dir
        tst.b 35(%a5)
        bne.w .Lstore\@
        cmpi.l #0x01000100,%d7
        beq.w .Ladd\@
        BANK 1,add,\dir
.Ladd\@:
        BANK 0,add,\dir
.Lstore\@:
        cmpi.l #0x01000100,%d7
        beq.w .Lmove\@
        BANK 1,move,\dir
.Lmove\@:
        BANK 0,move,\dir
        .endm

        .text
        .even
        .global og_mix_span
og_mix_span:
        PROLOGUE
        ENTRY 0

        .even
        .global og_mix_span_reverse
og_mix_span_reverse:
        PROLOGUE
        ENTRY 1

| A segment from the phase in d5: p, the table entries, its frames, then
| the loop in a6. At exactly `half` the window is the peak for one frame.
.Lspan_seg:
        move.l 12(%a5),%d1              | step
        cmp.l 24(%a5),%d5               | half
        bcc.w .Lspan_falling
        move.l %d5,%d2                  | rising: p = phase
        movea.l %d1,%a3
        move.l #0x00ffffff,%d0
        and.l %d2,%d0
        movea.l 16(%a5),%a4             | the attack half
| Long windows usually keep a whole source span in one envelope segment.
| Check its LAST used phase; if it fits, the next segment phase is unused
| and neither the division nor the segment-end construction is needed.
        cmpi.l #0x00020000,%d1
        bhi.s .Lspan_rising_split
        move.l 44(%sp),%d3
        sub.l %a1,%d3
        lsr.l #3,%d3
        subq.l #1,%d3
        mulu.l %d1,%d3
        add.l %d0,%d3
        cmpi.l #0x01000000,%d3
        bcs.w .Lspan_fit
.Lspan_rising_split:
        neg.l %d0
        add.l %d1,%d0
        addi.l #0x00ffffff,%d0
        divu.l %d1,%d0                  | k = ceil((2^24 - p mod 2^24) / step)
        move.l %d2,%d3
        moveq #23,%d4
        lsr.l %d4,%d3
        bclr #0,%d3                     | 2i
.Lspan_entry:
        adda.l %d3,%a4
        mvz.w (%a4)+,%d3                | left = t[i]
        mvz.w (%a4),%d4
        sub.l %d3,%d4                   | delta = t[i+1] - t[i]
.Lspan_go:
        move.l %d0,%d1
        lsl.l #3,%d1
        lea (%a1,%d1.l),%a2             | the segment's end
        cmpa.l 44(%sp),%a2
        bls.s 1f
        movea.l 44(%sp),%a2             | the span's last segment
1:      mulu.l 12(%a5),%d0
        add.l %d0,%d5                   | the next segment's phase
        swap %d3
        movea.l %d3,%a4                 | left << 16
        jmp (%a6)
.Lspan_falling:
        beq.w .Lspan_top
        move.l #0x80000000,%d2
        sub.l %d5,%d2                   | p = 2^31 - phase
        move.l %d1,%d0
        neg.l %d0
        movea.l %d0,%a3
        move.l #0x00ffffff,%d0
        and.l %d2,%d0
        movea.l 20(%a5),%a4             | the release half
        cmpi.l #0x00020000,%d1
        bhi.s .Lspan_falling_split
        move.l 44(%sp),%d3
        sub.l %a1,%d3
        lsr.l #3,%d3
        subq.l #1,%d3
        mulu.l %d1,%d3
        cmp.l %d3,%d0
        bcc.w .Lspan_fit
.Lspan_falling_split:
        divu.l %d1,%d0
        addq.l #1,%d0                   | k = (p mod 2^24) / step + 1
        move.l %d2,%d3
        moveq #23,%d4
        lsr.l %d4,%d3
        bclr #0,%d3                     | 2i
        bra.s .Lspan_entry
.Lspan_top:
        move.l %d5,%d3
        moveq #23,%d4
        lsr.l %d4,%d3                   | 2 * (half >> 24): half is a whole segment
        movea.l 16(%a5),%a4
        mvz.w (%a4,%d3.l),%d3           | left = attack[half >> 24], the peak
        moveq #0,%d4                    | delta 0
        moveq #1,%d0                    | one frame
        movea.l %d1,%a3
        move.l %d5,%d2                  | p: any, delta is 0
        bra.w .Lspan_go
.Lspan_fit:
        move.l %d2,%d3
        moveq #23,%d4
        lsr.l %d4,%d3
        bclr #0,%d3
        adda.l %d3,%a4
        mvz.w (%a4)+,%d3
        mvz.w (%a4),%d4
        sub.l %d3,%d4
        swap %d3
        movea.l %d3,%a4
        movea.l 44(%sp),%a2
        jmp (%a6)
.Lspan_next:
        cmpa.l 44(%sp),%a1
        bne.w .Lspan_seg
        movem.l (%sp),%d2-%d7/%a2-%a6
        lea 48(%sp),%sp
        rts

| Exact fused source-end seam: same Q31 window segments and PAN as above.
| Decode PCM and apply the accepted 128-frame convex source-end crossfade
| directly before PAN/window accumulation, avoiding the intermediate pairs.
| OgSpan's appended join_l/join_r/weight fields are at36/40/44. The saved
| register frame is56 bytes here;48(sp) holds the weight across segments.
| Weight advances/decrements once per source frame. All d2-d7/a2-a6 are
| preserved, and the old regular mixer remains unchanged.
        .macro SEAM_ENV
        move.l %d2,%d0
        lsr.l #8,%d0
        mulu.w %d4,%d0
        add.l %a4,%d0
        swap %d0
        add.l %a3,%d2
        .endm

| One channel of one frame: the sample in the low word of \reg.
        .macro SEAM_PUT reg, gain, scaled, op
        .if \scaled
        muls.w \gain,\reg
        asr.l #8,\reg
        .endif
        muls.w %d0,\reg
        \op\().l \reg,(%a1)+
        .endm

| One frame a pass for format \fmt (kernel.h; the pairs run as 3), upwards
| or, with \dir 1, downwards: a0 first moves past the first frame for the
| predecrementing reads. Chosen once a span: a6 takes the loop, then the
| first segment; each segment's frames end at a2.

| d1 is signed PCM; d3 is scratch. The result is a convex combination
| within int16 range, before PAN. Difference needs 32 bits (up to 65535).
        .macro SEAM_JOIN target
        ext.l %d1
        move.l \target(%a5),%d3
        sub.l %d1,%d3
        muls.l 48(%sp),%d3
        asr.l #7,%d3
        add.l %d3,%d1
        .endm

        .macro SEAM_LOOP fmt, scaled, op, dir=0
        lea 1f(%pc),%a6
        bra.w .Lseam_span_seg
1:      SEAM_ENV
        .if \fmt == 0
        move.b (%a0),%d1
        lsl.l #8,%d1
        move.b 1(%a0),%d1
        .else
        move.w (%a0),%d1
        .endif
        SEAM_JOIN 36
        .if (\fmt & 1) == 0
        .if \scaled
        move.l %d1,%d3
        SEAM_PUT %d1,%d6,1,\op
        SEAM_PUT %d3,%d7,1,\op
        .else
        muls.w %d0,%d1
        \op\().l %d1,(%a1)+
        \op\().l %d1,(%a1)+
        .endif
        .else
        SEAM_PUT %d1,%d6,\scaled,\op
        .if \fmt == 1
        move.l 2(%a0),%d1
        lsr.l #8,%d1
        .else
        move.w 2(%a0),%d1
        .endif
        SEAM_JOIN 40
        SEAM_PUT %d1,%d7,\scaled,\op
        .endif
        .if \dir
        subq.l #1,48(%sp)
        .if \fmt == 0
        subq.l #3,%a0
        .elseif \fmt == 1
        subq.l #6,%a0
        .elseif \fmt == 2
        subq.l #2,%a0
        .else
        subq.l #4,%a0
        .endif
        .else
        addq.l #1,48(%sp)
        .if \fmt == 0
        addq.l #3,%a0
        .elseif \fmt == 1
        addq.l #6,%a0
        .elseif \fmt == 2
        addq.l #2,%a0
        .else
        addq.l #4,%a0
        .endif
        .endif
        cmpa.l %a2,%a1
        bne.w 1b
        bra.w .Lseam_span_next
        .endm


| The four formats for one PAN scaling and add/store; the format is in d0.
        .macro SEAM_BANK scaled, op, dir=0
        subq.l #2,%d0
        bcs.w .Lseam_pcm24\@
        beq.w .Lseam_mono16\@
        SEAM_LOOP 3,\scaled,\op,\dir
.Lseam_mono16\@:
        SEAM_LOOP 2,\scaled,\op,\dir
.Lseam_pcm24\@:
        addq.l #1,%d0
        beq.w .Lseam_stereo24\@
        SEAM_LOOP 0,\scaled,\op,\dir
.Lseam_stereo24\@:
        SEAM_LOOP 1,\scaled,\op,\dir
        .endm

| The span into registers (above), its end on the stack; the format is
| left in d0.
        .macro SEAM_PROLOGUE
        lea -56(%sp),%sp
        movem.l %d2-%d7/%a2-%a6,(%sp)
        movea.l 60(%sp),%a5
        movea.l (%a5),%a0
        movea.l 4(%a5),%a1
        move.l 8(%a5),%d5
        mvz.w 32(%a5),%d0
        lsl.l #3,%d0
        lea (%a1,%d0.l),%a2
        move.l %a2,44(%sp)
        move.l 28(%a5),%d7
        move.l %d7,%d6
        swap %d6
        move.l 44(%a5),%d0
        move.l %d0,48(%sp)
        mvz.b 34(%a5),%d0
        .endm

| The loops for one direction: store or add, PAN scaled or not.
        .macro SEAM_ENTRY dir
        tst.b 35(%a5)
        bne.w .Lseam_store\@
        cmpi.l #0x01000100,%d7
        beq.w .Lseam_add\@
        SEAM_BANK 1,add,\dir
.Lseam_add\@:
        SEAM_BANK 0,add,\dir
.Lseam_store\@:
        cmpi.l #0x01000100,%d7
        beq.w .Lseam_move\@
        SEAM_BANK 1,move,\dir
.Lseam_move\@:
        SEAM_BANK 0,move,\dir
        .endm

