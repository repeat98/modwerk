"""Generate the exact integer PAN curve; no firmware or floating point."""
import argparse
import math
from pathlib import Path

TARGET = Path(__file__).resolve().parents[1] / 'support/pan_gains.h'


def source():
    values = []
    for width in range(129):
        for position in range(2 * width + 1):
            gain = math.isqrt(((128 + width - position) << 16) // (128 + width))
            # Position0 is exactly unity and decoded explicitly by the caller.
            values.append(0 if gain == 256 else gain)
    assert len(values) == 129 * 129 and max(values) <= 255
    rows = ['    ' + ','.join(str(v) for v in values[i:i + 32]) + ','
            for i in range(0, len(values), 32)]
    return '\n'.join([
        '/* SPDX-License-Identifier: GPL-3.0-or-later */',
        '/* Generated by qualification/generate_pan_gains.py from integer math.',
        ' * Row width starts at width*width, with 2*width+1 positions.',
        ' * Position0 is unity256; its stored zero is never used for that endpoint. */',
        '#ifndef FRACT_PAN_GAINS_H', '#define FRACT_PAN_GAINS_H', '#include <stdint.h>',
        '#ifndef OG_PAN_STORAGE', 'extern const uint8_t og_pan_gains[16641];', '#else',
        'const uint8_t og_pan_gains[16641] = {', *rows, '};', '#endif', '#endif', ''])


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = source()
    if args.check:
        if TARGET.read_text() != expected:
            raise SystemExit('PAN gains differ from the exact integer construction')
        print('PASS: all16641 PAN entries match the integer construction')
    else:
        TARGET.write_text(expected)
