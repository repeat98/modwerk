#!/usr/bin/env python3
"""Rebuild grain_core.s (the unit manifest.py links) from grain_machine.c, or --check. As AMIGA's generate.py."""
import pathlib
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
# The module is staged under sdk/octabam/modules/ for builds: find sdk/ from either place.
SDK = next(p for p in HERE.parents if (p / 'machines/octatrack/include/modwerk_events.h').exists())
sys.path.insert(0, str(SDK / 'runtime'))
import m68k_codegen

FLAGS = ['-mcpu=54455', '-msoft-float', '-O2', *m68k_codegen.FLAGS, '-ffreestanding', '-fno-builtin',
         '-fno-common', '-fno-jump-tables', '-fno-asynchronous-unwind-tables',
         '-fno-ident', '-fomit-frame-pointer', '-I', str(SDK / 'machines/octatrack/include')]


def generate():
    with tempfile.TemporaryDirectory() as td:
        asm = pathlib.Path(td) / 'grain_machine.s'
        # A relative source name: the compiler writes it into the assembly's line markers, and the check must pass in any checkout.
        subprocess.run(['m68k-elf-gcc', *FLAGS, '-S', 'grain_machine.c', '-o', str(asm)], check=True, cwd=HERE)
        obj = asm.with_suffix('.o')
        subprocess.run(['m68k-elf-as', '-mcpu=54455', str(asm), '-o', str(obj)], check=True)
        m68k_codegen.check_mcf54455([obj])
        return '| Generated by generate.py from grain_machine.c; edit that.\n' + asm.read_text()


if __name__ == '__main__':
    source = generate()
    dest = HERE / 'grain_core.s'
    if '--check' in sys.argv:
        if not dest.exists() or source != dest.read_text():
            sys.exit('grain_core.s is stale: run generate.py')
        print('grain_core.s matches grain_machine.c')
    else:
        dest.write_text(source)
        print('wrote', dest)
