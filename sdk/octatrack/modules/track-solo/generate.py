#!/usr/bin/env python3
"""Generate the native assembly from original C with the shared ColdFire guard."""
from pathlib import Path
import subprocess
import sys
import tempfile

HERE = Path(__file__).resolve().parent
SDK = next((parent for parent in HERE.parents if (parent / 'runtime/m68k_codegen.py').is_file()), None)
if SDK is None:
    raise RuntimeError('Could not locate the repository SDK runtime tools')
sys.path.insert(0, str(SDK / 'runtime'))
import m68k_codegen

FLAGS = ['-mcpu=54455', '-msoft-float', '-Os', '-std=c99', '-ffreestanding',
         '-fno-builtin', '-fno-common', '-fno-jump-tables', '-fno-zero-initialized-in-bss',
         '-fno-asynchronous-unwind-tables', '-fno-unwind-tables', '-fno-ident',
         '-fomit-frame-pointer', '-Wall', '-Wextra', '-Werror', *m68k_codegen.FLAGS]

with tempfile.TemporaryDirectory() as tmp:
    asm, obj = Path(tmp) / 'core.s', Path(tmp) / 'core.o'
    subprocess.run(['m68k-elf-gcc', *FLAGS, '-S', str(HERE / 'track_solo.c'), '-o', str(asm)], check=True)
    # The native linked unit is a single initialized .text extent, as other
    # ColdFire modules: do not rely on a card build's .bss initialization.
    result = '| Generated by generate.py from track_solo.c; edit the C source.\n'
    result += asm.read_text().replace('\t.data', '\t.text')
    asm.write_text(result)
    subprocess.run(['m68k-elf-as', '-mcpu=54455', str(asm), '-o', str(obj)], check=True)
    m68k_codegen.check([obj])
    m68k_codegen.check_mcf54455([obj])
    dest = HERE / 'core.s'
    if '--check' in sys.argv:
        if not dest.exists() or dest.read_text() != result:
            raise SystemExit('core.s is stale; run generate.py')
        print('core.s matches guarded ColdFire compilation')
    else:
        dest.write_text(result)
        print('Generated core.s')
