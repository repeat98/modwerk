"""Envelopes' AMP ATK curve: knob value -> amp envelope rate word (20-bit coefficient).

The amp attack is a linear ramp from silence (-128) to the top (127), 255 levels. A
coefficient c (e = c[19:16], m = c[15:0]) moves the level step / 2^23 levels per tick
(2 samples at 48 kHz), step = ((0x7FFFFFFF - (m << 14)) >> e) - 32768, as the OS times its
linear segments. The curve:

    0          instant (c = 0)
    1..25      0.2 ms steps, 0.2 .. 5 ms
    26..45     0.5 ms steps, 5.5 .. 15 ms
    46..127    x r a step, 15 ms .. 29.89 s (stock's ATK 127)

Stored packed in 16 bits, e << 12 | m >> 4 (m rounded to a multiple of 16: at most 2.3e-4 off in
step); unpacked as (u >> 12) << 16 | (u & 0xfff) << 4. Prints the C table for src/envelopes.c;
--check prints each value's time back from the packed table.
"""
import sys

TICKS_PER_MS = 24.0          # 48 kHz, 2 samples a tick
HW_SPEED = 0.957             # the unit's amp attack runs 0.957x the OS timing model (EV06, 6 Nov 2026)
F_LEVELS, F_HW_SPEED = 127, 1.0    # the filter attack: 0 -> 127 levels, at the model's speed (EV13: 1.00x, 3 ms..390 ms)
TOP_MS = 29889.0             # stock ATK 127's full ramp
LEVELS = 255


def curve_ms():
    t = [0.0]
    for k in range(1, 26):
        t.append(0.2 * k)
    for k in range(26, 46):
        t.append(5.0 + 0.5 * (k - 25))
    r = (TOP_MS / t[45]) ** (1.0 / (127 - 45))
    for k in range(46, 128):
        t.append(t[45] * r ** (k - 45))
    return t


def step_of(c):
    e, m = (c >> 16) & 15, c & 0xFFFF
    return ((0x7FFFFFFF - (m << 14)) >> e) - 32768


def encode(ms, levels=LEVELS, hw=HW_SPEED, packed=True):
    if ms <= 0:
        return 0
    ticks = ms / hw * TICKS_PER_MS - 1           # model ticks the unit plays in ms; +1 as the OS counts
    s = int(round(levels * 2 ** 23 / ticks)) + 32768
    n = 32 - s.bit_length() - 1            # clz(s) - 1: s << n has bit 30 as its top bit
    m = (0x7FFFFFFF - (s << n)) >> 14
    if packed:
        m = min((m + 8) >> 4, 0xFFF) << 4  # packed: the low 4 bits of m are dropped
    assert 0 <= n <= 15 and 0 <= m <= 0xFFFF, (ms, s, n, m)
    return (n << 16) | m


def pack(c):
    return (c >> 16) << 12 | (c & 0xFFFF) >> 4


def ramp_ms(c, levels=LEVELS, hw=HW_SPEED):
    return ((levels << 23) / step_of(c) + 1) / TICKS_PER_MS * hw


def main():
    t = curve_ms()
    table = [encode(x) for x in t]
    ftable = [encode(x, F_LEVELS, F_HW_SPEED, False) for x in t]
    if '--check' in sys.argv:
        for k, (want, c) in enumerate(zip(t, table)):
            got = ramp_ms(c)
            err = 0 if want == 0 else (got - want) / want * 100
            print(f'{k:3d} want {want:10.3f} ms  c {c:05x}  got {got:10.3f} ms  {err:+.2f} %')
        for k, (want, c) in enumerate(zip(t, ftable)):
            got = ramp_ms(c, F_LEVELS, F_HW_SPEED)
            err = 0 if want == 0 else (got - want) / want * 100
            print(f'{k:3d} want {want:10.3f} ms  c {c:05x}  got {got:10.3f} ms  {err:+.2f} %')
        return
    print('// Generated by tools/atk_table.py: AMP ATK knob -> linear rate coefficient, packed.')
    print('static const uint16_t atk_rate[128] = {')
    for i in range(0, 128, 8):
        print('    ' + ', '.join(f'0x{pack(c):04x}' for c in table[i:i + 8]) + ',')
    print('};')
    print()
    print('// The same curve for FILTER ATK (0 -> 127 levels), read by stock through the lea at')
    print('// 0x4010d2a8 (attack record and the state counter alike), so full 32-bit words.')
    print('const uint32_t envelopes_flt_atk[128] __attribute__((aligned(4))) = {')
    for i in range(0, 128, 8):
        print('    ' + ', '.join(f'0x{c:05x}' for c in ftable[i:i + 8]) + ',')
    print('};')


if __name__ == '__main__':
    main()
