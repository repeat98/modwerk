import math

FS = 48000
BLOCK = 32

g = [round(math.tan(math.pi * 20 * 900 ** (f / 127) / FS) * 65536) for f in range(128)]
k = [round(2 * 0.125 ** (r / 15) * 65536) for r in range(16)]
d = [min(0x7FFFFFFF, round(math.exp(-(BLOCK / FS) / (0.004 * 750 ** (x / 126))) * 2 ** 31)) for x in range(127)]


def rows(v, n=8, fmt='%d'):
    return ',\n'.join('    ' + ', '.join(fmt % x for x in v[i:i + n]) for i in range(0, len(v), n))


print('// Generated by tools/tables.py: do not edit.')
print('// FRQ 0..127 -> tan(pi fc / 48 kHz) in Q16, fc = 20 Hz * 900^(FRQ/127) (20 Hz .. 18 kHz).')
print('static const uint32_t SL_G[128] = {\n' + rows(g) + '\n};')
print('// RES 0..15 -> k = 1/Q in Q16, 2.0 (Q 0.5) down to 0.25 (Q 4).')
print('static const uint32_t SL_K[16] = {\n' + rows(k) + '\n};')
print("// DEC 0..126 -> the decay's gain a 32-frame block in Q31, time constant 4 ms * 750^(DEC/126) (4 ms .. 3 s).")
print('static const uint32_t SL_DEC[127] = {\n' + rows(d, 6, '0x%08x') + '\n};')
