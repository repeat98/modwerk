import math

FS = 48000
BLOCK = 32
BLOCK_S = BLOCK / FS
Q31 = 2 ** 31
Q28 = 2 ** 28

g = [round(math.tan(math.pi * 20 * 900 ** (f / 127) / FS) * 65536) for f in range(128)]
# DEC 0..62 (63 is INF): time constant 4 ms * 750^(DEC/62), 4 ms .. 3 s
d = [min(0x7FFFFFFF, round(math.exp(-BLOCK_S / (0.004 * 750 ** (x / 62))) * Q31)) for x in range(63)]

def coef(ms):
    return round(math.exp(-BLOCK_S / (ms / 1000)) * Q31)


def rows(v, n=8, fmt='%d'):
    return ',\n'.join('    ' + ', '.join(fmt % x for x in v[i:i + n]) for i in range(0, len(v), n))


print('// Generated by tools/tables.py: do not edit.')
print('// BAS and the band top 0..127 -> tan(pi fc / 48 kHz) in Q16, fc = 20 Hz * 900^(x/127) (20 Hz .. 18 kHz).')
print('static const uint32_t SL_G[128] = {\n' + rows(g) + '\n};')
print("// DEC 0..62 -> the decay's gain a 32-frame block in Q31, time constant 4 ms * 750^(DEC/62) (4 ms .. 3 s).")
print('static const uint32_t SL_DEC[63] = {\n' + rows(d, 6, '0x%08x') + '\n};')
print('// The detectors, a 32-frame block: release 20 ms; the slow attack 15 ms.')
print('#define SL_REL 0x%08x' % coef(20))
print('#define SL_SLOW_ATK 0x%08x' % (Q31 - 1 - coef(15)))
print('#define SL_HOLD_BLOCKS %d' % round(0.010 / BLOCK_S))
