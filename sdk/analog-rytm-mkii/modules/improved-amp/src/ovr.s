        | Stock's only reader of AMP OVR (param id 59, sound index 36) is in amp_env_commands
        | (0x40109940), once a voice a block: `move.w 6(%a4),%d0; add.l %d0,%d0; move.w %d0,42(%a5)`
        | at 0x40109b14 (10 bytes), the CV twice the live word, linear. The stage gives most of its
        | distortion in the first steps, so this reader looks the CV up instead, in a 129-point table
        | that spreads the stage's THD rise evenly over the knob (tools/ovr_table.py), interpolated on
        | the word's low byte so smoothing, LFOs and performance moves stay smooth. OVR 0 and 127 send
        | stock's CV; the knob's text stays stock's 0..127.

