// ---- the voice's amp level, followed from the records ----
//
// A record is a level word (W, start S, target T as signed bytes) and a rate word: mode
// [31:28], sub-block nibble, flags [23:20] (0 linear, 1 one-pole) and a 20-bit
// coefficient. Modes as measured on the unit: B and 3 head for T from the current level,
// F (and 7) load S first, 9 changes the rate only, A and 2 freeze, 0 and 8 send nothing
// (the running segment goes on). Per tick (2 samples) a linear segment moves step / 2^23
// levels; a one-pole one keeps (2^31 - step) / 2^31 of its distance to T.
//
// Levels are kept in 1/65536, from silence (-128) at boot: an idle voice gets no records.
// The follower errs low: a one-pole block takes 16 x step / 2^31 of the distance at the unit's
// measured decay speed (HW_DECAY), slightly more than the hardware's 1 - (1 - x)^16, so a
// falling level is followed at or below the real one; the attack is followed at the model's
// speed, slower than the unit's (HW_ATTACK). So the attack is never thought done early.
// (Stock's amp sends no rising one-pole segment.)
struct amp {
    int32_t level, target;
    uint32_t step;
    uint8_t one_pole, frozen;
};
#define SILENT (-128 * 65536)
static struct amp amps[8] = {
    { SILENT, SILENT, 0, 0, 0 }, { SILENT, SILENT, 0, 0, 0 }, { SILENT, SILENT, 0, 0, 0 },
    { SILENT, SILENT, 0, 0, 0 }, { SILENT, SILENT, 0, 0, 0 }, { SILENT, SILENT, 0, 0, 0 },
    { SILENT, SILENT, 0, 0, 0 }, { SILENT, SILENT, 0, 0, 0 },
};

static uint32_t atk_coeff(int k)
{
    uint32_t u = atk_rate[k < 0 ? 0 : k > 127 ? 127 : k];
    return (u >> 12) << 16 | (u & 0xfff) << 4;
}

static uint32_t rate_step(uint32_t c)
{
    uint32_t e = c >> 16 & 15, m = c & 0xffff;
    return ((0x7fffffffu - (m << 14)) >> e) - 32768u;
}

__attribute__((noinline)) static void follow(struct amp *a, uint32_t rate, uint32_t lw)
{
    unsigned mode = rate >> 28;
    int32_t d;
    uint32_t ad, move;

    if (mode == 0xa || mode == 0x2) {
        a->frozen = 1;
    } else if (mode && mode != 8) {
        if (mode & 4)
            a->level = (int32_t)(int8_t)(lw >> 8) * 65536;
        if (mode != 9)
            a->target = (int32_t)(int8_t)lw * 65536;
        a->step = rate_step(rate & 0xfffff);
        a->one_pole = rate >> 20 & 1;
        a->frozen = 0;
    }
    if (a->frozen)
        return;
    d = a->target - a->level;
    ad = d < 0 ? (uint32_t)-d : (uint32_t)d;
    if (!ad)
        return;
    if (!a->one_pole) {
        move = a->step >> 3;                    // 16 ticks: step x 16 x 65536 / 2^23
        if (!move)
            move = 1;                           // a rate this slow still ends
        if (move >= ad) {
            a->level = a->target;
            return;
        }
        ad -= move;
    } else {
        // 16 ticks: 16 x step / 2^31, in 1/65536, at the unit's decay speed (1 / 0.918),
        // rounded up (step >> 6 keeps the fraction for slow decays); 2^27 and up is instant.
        move = a->step >= (1u << 27) ? 65536 : (((a->step >> 6) * 1116) >> 15) + 1;
        if (move >= 65536) {
            a->level = a->target;
            return;
        }
        ad -= (ad >> 8) * move >> 8;
    }
    a->level = d < 0 ? a->target + (int32_t)ad : a->target - (int32_t)ad;
}

// ---- HLD in steps ----
// The hold is counted on the musical clock: a step of a track is SPEED_PULSES[speed] pulses of
// 900,000 clock units (5,400,000 a step at 1x), whatever the tempo and whether the clock is the
// Rytm's own or a master's. pre-fade.c reads the clock once a block and leaves what it moved
// in SCAN_DELTA; a quarter of that is added to a holding voice's HOLD_ACC.
#define SEQ_PATTERN (*(volatile int8_t *)SEQ_PATTERN_AT)
#define PATTERN(p) ((const volatile int8_t *)PATTERNS_AT + 85760 * (p))
#define SPEED_PULSES ((const int32_t *)SPEED_PULSES_AT)    // 3, 4, 6, 8, 12, 24, 48 pulses a step
#define PAT_SCALE 85689                                    // 1: ADVANCED, each track its own speed
#define PAT_SPEED 85690                                    // 0..6, as SPEED_PULSES
#define TRACK_BYTES 917
#define TRK_SPEED 711
#define VOICE_TRACK ((const volatile uint8_t *)0x40291138) // [voice] the track it plays
#define HOLD_STEPS improved_amp_hold_steps
#define HOLD_FIRST 0xffffffffu                             // HOLD_ACC: the trig's block, nothing counted yet

// The pulses in a step of the track voice v plays: the pattern's speed, or the track's own in
// ADVANCED scale.
static uint32_t voice_pulses(int v)
{
    int track = VOICE_TRACK[v & 7], p = SEQ_PATTERN, speed = 2;

    if (p >= 0 && p < 128) {
        const volatile int8_t *pattern = PATTERN(p);
        speed = pattern[PAT_SCALE] == 1 && (unsigned)track < 12 ? pattern[TRACK_BYTES * track + TRK_SPEED]
                                                                 : pattern[PAT_SPEED];
    }
    if (speed < 0 || speed > 6)
        speed = 2;
    return (uint32_t)SPEED_PULSES[speed];
}

// The writer's skip state (amp-write.s reads it for every voice every block) is in hot.h:
// GATE_STILL the voices whose last record left the level follower unchanged, GATE_RATE and GATE_LW
// that record's two words, GATE_ZERO the voices among them whose record was 0/0.

// Called by improved_amp_write (amp-write.s) for every voice every block, after stock's state
// machine and before the record is stored; returns the rate word to store. st[0] is the
// voice's state (st[1], stock's own hold counter in ticks, is not used); snd[0] is the track's
// ATK, snd[2] its HLD. HOLD_ACC(v) is what the musical clock has moved since the block after
// the trig, in quarters: as stock's counter it reads 0 in the first block that holds.
uint32_t improved_amp_voice(int32_t v, volatile int32_t *st, const volatile int8_t *snd, uint32_t rate,
                     uint32_t lw)
{
    struct amp *a = &amps[v & 7], was = *a;
    int h = snd[2];
    uint32_t bit = 1u << (v & 7);

    // The attack's records (the trig's, then each held block's): this module's ATK curve.
    if (lw == LEVEL_ATTACK || lw == LEVEL_HOLD)
        rate = (rate & 0xfff00000u) | atk_coeff(snd[0]);

    if (lw == LEVEL_ATTACK) {
        st[0] = h == HLD_AUTO ? 1 : 2;
        HOLD_ACC(v & 7) = HOLD_FIRST;
    } else if (lw == LEVEL_HOLD || (uint32_t)(st[0] - 1) < 2u) {
        // Every block of the gate and hold states counts: the ones whose record the pre-fade
        // has taken for its fade too (such a voice is not left to the writer's skip, below).
        uint32_t acc = HOLD_ACC(v & 7), moved = SCAN_DELTA >> 2;

        if (acc == HOLD_FIRST)
            acc = 0;
        else if (acc + moved < acc || acc + moved == HOLD_FIRST)
            acc = HOLD_FIRST - 1;       // as long as it can count
        else
            acc += moved;
        HOLD_ACC(v & 7) = acc;
        if (lw == LEVEL_HOLD && h == HLD_AUTO && st[0] == 2) {
            st[0] = 1;          // turned to AUTO while held: the gate (set at the trig) ends it
        } else if (lw == LEVEL_HOLD && h != HLD_AUTO && (uint32_t)(st[0] - 1) < 3u) {
            // States 1 and 2 send the continued attack; 3 here is a gate that ended in this
            // block, on a voice whose HLD was turned from AUTO to a value: it holds its steps
            // from the trig too. (With HLD at AUTO a 3 is the note's end and is left alone.) The
            // track's speed is read only once the count has reached the hold at the fastest one.
            uint32_t steps = h > 0 ? (uint32_t)HOLD_STEPS[h] : 0;

            st[0] = a->level >= TOP && acc >= steps * 3u && acc >= steps * voice_pulses(v) ? 3 : 2;
        }
    }
    follow(a, rate, lw);
    // A record that is neither attack word and left the follower as it was does the same next
    // time: until the record changes, the writer skips this call (amp-write.s). Idle voices and
    // a decay that has reached its end get the same record every block. A voice in its gate or
    // hold whose record the pre-fade has taken is not skipped: its hold goes on counting.
    if (lw != LEVEL_ATTACK && lw != LEVEL_HOLD && (uint32_t)(st[0] - 1) >= 2u &&
        a->level == was.level && a->target == was.target &&
        a->step == was.step && a->one_pole == was.one_pole && a->frozen == was.frozen) {
        GATE_RATE(v & 7) = rate;
        GATE_LW(v & 7) = lw;
        GATE_STILL |= bit;
        // An idle voice's record is 0/0: the writer tells that from the two words alone.
        if (rate == 0 && lw == 0)
            GATE_ZERO |= bit;
        else
            GATE_ZERO &= ~bit;
    } else {
        GATE_STILL &= ~bit;
        GATE_ZERO &= ~bit;
    }
    return rate;
}

// ---- FUNC + turn on HOLD: 0, the step grid (0.125 .. 64 steps), AUTO ----
static int32_t hold_jump(const void *fn, int32_t value, int32_t delta, int32_t min, int32_t max,
                         int32_t def)
{
    static const int8_t pos[] = { 0, 19, 25, 33, 37, 42, 49, 53, 61, 66, 78, 90, 102, 114, HLD_AUTO };  // HOLD_STEPS' grid
    int v = value >> 8, i;

    (void)fn, (void)min, (void)max, (void)def;
    if (delta > 0) {
        for (i = 0; i < (int)sizeof pos; i++)
            if (pos[i] > v)
                return pos[i] << 8;
    } else {
        for (i = (int)sizeof pos - 1; i >= 0; i--)
            if (pos[i] < v)
                return pos[i] << 8;
    }
    return v << 8;
}

// The records are built at boot; the jump goes in once and is checked at the UI's rate.
void improved_amp_tick(void *ctrl)
{
    (void)ctrl;
    if (JUMP_INVOKER(ID_A_HLD) != (word_t)hold_jump) {
        JUMP_MANAGER(ID_A_HLD) = STOCK_MANAGER;
        JUMP_INVOKER(ID_A_HLD) = (word_t)hold_jump;
    }
}

// ---- times on the knobs ----
__attribute__((noinline)) static char *put_uint(char *p, uint32_t v)
{
    char t[10];
    int n = 0;
    do
        t[n++] = (char)('0' + v % 10);
    while ((v /= 10) && n < 10);
    while (n)
        *p++ = t[--n];
    return p;
}

__attribute__((noinline)) static void put_text(char *p, const char *s)
{
    while ((*p++ = *s++))
        ;
}

// ticks of 2 samples: "0", "0.2ms", "9.8ms", "87ms", "1234ms", "2.1s", "15.5s", "100s".
__attribute__((noinline)) static void put_time(char *p, uint32_t ticks)
{
    uint32_t ms10, ms, s10;

    if (ticks > 40000000u)
        ticks = 40000000u;
    ms10 = (ticks * 10 + 12) / 24;
    if (!ms10) {
        put_text(p, "0");
        return;
    }
    if (ms10 < 200) {                   // tenths up to 20 ms: ATK's 0.5 ms steps stay visible
        p = put_uint(p, ms10 / 10);
        *p++ = '.';
        p = put_uint(p, ms10 % 10);
        put_text(p, "ms");
        return;
    }
    // Each unit rounds from the ticks, not from the unit below it (31.46 ms shows 31ms).
    ms = (ticks + 12) / 24;
    if (ms < 2000) {                    // whole ms up to 2 s: HLD's 6 % steps stay apart
        put_text(put_uint(p, ms), "ms");
        return;
    }
    s10 = (ticks + 1200) / 2400;
    if (s10 < 1000) {
        p = put_uint(p, s10 / 10);
        *p++ = '.';
        p = put_uint(p, s10 % 10);
        put_text(p, "s");
        return;
    }
    put_text(put_uint(p, (ticks + 12000) / 24000), "s");
}

// A hold in steps from HOLD_STEPS, three digits: "0", "0.005", "0.080", "1.64", "14.9", "21.0",
// "124". A hold of whole eighths of a step below 100, which the grid's 13 are and no other value
// is, drops the zeros at its end: "0.125", "0.5", "1", "1.5", "64".
__attribute__((noinline)) static void put_steps(char *p, uint32_t cq)
{
    uint32_t q, d;
    char *end;

    if (!cq) {
        put_text(p, "0");
        return;
    }
    // Each unit rounds from the table's value, not from the unit below it.
    q = (cq + 112) / 225;                       // thousandths of a step
    if (!q)
        q = 1;                                  // a hold there is never reads as none
    if (q < 1000) {
        *p++ = '0';
        *p++ = '.';
        *p++ = (char)('0' + q / 100);
        *p++ = (char)('0' + q / 10 % 10);
        *p++ = (char)('0' + q % 10);
    } else if ((d = (cq + 1125) / 2250) < 1000) {       // hundredths, below 10
        p = put_uint(p, d / 100);
        *p++ = '.';
        *p++ = (char)('0' + d / 10 % 10);
        *p++ = (char)('0' + d % 10);
    } else if ((d = (cq + 11250) / 22500) < 1000) {     // tenths, below 100
        p = put_uint(p, d / 10);
        *p++ = '.';
        *p++ = (char)('0' + d % 10);
    } else {
        put_uint(p, (cq + 112500) / 225000)[0] = 0;
        return;
    }
    end = p;
    if (cq % 28125 == 0) {                      // on the grid: every form above has a point before its last digits
        while (end[-1] == '0')
            end--;
        if (end[-1] == '.')
            end--;
    }
    *end = 0;
}

// log2(y) x 65536, y > 0.
__attribute__((noinline)) static int32_t log2_q16(uint32_t y)
{
    int32_t n = 31, bit, f = 0;
    uint32_t m;

    while (!(y & 0x80000000u)) {
        y <<= 1;
        n--;
    }
    m = y >> 16;
    for (bit = 15; bit >= 0; bit--) {
        m = (m * m) >> 15;
        if (m >= 65536) {
            m >>= 1;
            f |= 1 << bit;
        }
    }
    return (n << 16) + f;
}

// A one-pole segment's ticks to fall 60 dB: ln 1000 / -ln p, p = 1 - step / 2^31 a tick.
// The OS's own (0x4011e85c) runs on the MAC in fractional mode, which only the audio
// interrupt sets, so it reads wrong from the UI. Small steps: -ln p = x (1 + x / 2), x =
// step / 2^31 (the next term is under 0.01 %); larger: log2, 1/65536 resolution.
__attribute__((noinline)) static uint32_t t60_ticks(uint32_t c)
{
    uint32_t s = rate_step(c), d;
    int32_t q;

    if (s < 16)
        return 0x7fffffffu;
    if (s < (1u << 25)) {
        d = (s >> 4) + (s >> 18) * (s >> 18);   // x (1 + x / 2), in 2^-27
        return 927143219u / d;                  // ln 1000 x 2^27
    }
    if (s >= 0x7fff0000u)
        return 0;
    q = (31 << 16) - log2_q16(0x7fffffffu - s);
    return q > 0 ? 653118u / (uint32_t)q : 0x7fffffffu;   // log2 1000 x 65536
}

// A linear segment's ticks over levels, as the OS counts them (0x4011e7d6).
__attribute__((noinline)) static uint32_t linear_ticks(uint32_t levels, uint32_t c)
{
    uint32_t s = rate_step(c);
    return s ? (levels << 23) / s + 1 : 0x7fffffffu;
}

// ticks x f / 1024, rounded, without overflow (ticks up to 0x7fffffff). Rounded, not
// floored, so short attacks (a few dozen ticks) read their nearest tenth.
static uint32_t scaled(uint32_t ticks, uint32_t f)
{
    return (ticks >> 10) * f + (((ticks & 1023) * f + 512) >> 10);
}

static int improved_amp_text(struct core_text *t)
{
    int v = t->value >> 8;

    if (v < 0)
        v = 0;
    if (v > 127)
        v = 127;
    switch (t->id) {
    case ID_A_ATK:
        put_time(t->buf, scaled(linear_ticks(255, atk_coeff(v)), HW_ATTACK));
        break;
    case ID_A_HLD:
        if (v == HLD_AUTO)
            put_text(t->buf, "AUTO");
        else
            put_steps(t->buf, v ? (uint32_t)HOLD_STEPS[v] : 0);
        break;
    case ID_A_DEC:
        if (v == 127)
            put_text(t->buf, "INF");
        else
            put_time(t->buf, scaled(t60_ticks(AMP_DECAY[v] & 0xfffff), HW_DECAY));
        break;
    case ID_F_ATK:
        put_time(t->buf, linear_ticks(127, improved_amp_flt_atk[v]));
        break;
    case ID_F_DEC:
    case ID_F_REL:
        put_time(t->buf, t60_ticks(FLT_DECAY[v] & 0xfffff));
        break;
    default:
        return CORE_TEXT_PASS;
    }
    return CORE_TEXT_DONE;
}

const struct core_param improved_amp_params = { ID_F_ATK, ID_A_DEC, 0, 0, improved_amp_text };
