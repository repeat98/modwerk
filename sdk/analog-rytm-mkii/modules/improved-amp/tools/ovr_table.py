# Improved AMP: the AMP OVR knob's CV table (src/ovr.s), Nathaniel Pavel.
#
# Stock sends the overdrive stage a CV of twice the knob's live word, linear, and most of the stage's
# distortion arrives in the first few steps (S1 sweep, Rytm MKII, 8 Nov 2026: THD 6.1 % at 0, 13.5 % at 4,
# 22.4 % at 12, 38.5 % at 127). This table spreads the THD rise evenly over the knob: knob k gives the stock
# value whose THD rise is k/127 of the whole, so the first stock step takes about eight knob steps.
#
#   python3 tools/ovr_table.py SWEEP.json        # prints the C table for src/ovr.s
#
# SWEEP.json: the sweep's list of {"v": 0..127, "thd_pct": ...} (one hit per stock OVR value, a sustained
# sine, MAIN OUT). The table: 129 words, f(k) = the stock-equivalent value x 512, f(0) = 0, f(127) = 0xfe00
# (stock's full scale), f(128) = 0xffff for the live word's top (0x7fff); src/ovr.s interpolates between them.
import json
import sys


def main(path):
    sweep = sorted(json.load(open(path)), key=lambda e: e["v"])
    assert [e["v"] for e in sweep] == list(range(128)), "one point per stock value 0..127"
    thd, top = [], 0.0
    for e in sweep:                      # rising only: noise must not fold the curve back
        top = max(top, e["thd_pct"])
        thd.append(top)
    rise = [(t - thd[0]) / (thd[-1] - thd[0]) for t in thd]
    table = []
    for k in range(128):
        want = k / 127
        v = 0
        while v < 126 and rise[v + 1] < want:
            v += 1
        span = rise[v + 1] - rise[v]
        value = v + ((want - rise[v]) / span if span > 0 else 0)
        table.append(min(0xfe00, round(max(0.0, min(127.0, value)) * 512)))
    table[0], table[127] = 0, 0xfe00
    for a, b in zip(table, table[1:]):
        assert b >= a, "the table must rise"
    table.append(0xffff)
    print("        | Generated by tools/ovr_table.py from the S1 sweep: knob k -> CV, 129 words.")
    for i in range(0, 129, 8):
        print("        .short  " + ", ".join("0x%04x" % w for w in table[i:i + 8]))


if __name__ == "__main__":
    main(sys.argv[1])
