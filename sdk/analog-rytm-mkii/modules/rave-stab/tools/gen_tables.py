"""Write src/ra_tables.h: SY RAVE's chords.

Run from the module folder: python3 tools/gen_tables.py. Every number here is this
module's own; no instrument's tables, samples or code."""
import math, os

# Six notes a chord, in cents above the root. EURK is the chord a musician found in HH
# Alloy's CLSD set two octaves down (its squares at 317, 451, 538, 697, 829 and 1011 Hz),
# kept with its own detuning.
EURK = [round(1200 * math.log2(f / 317.0)) for f in (317, 451, 538, 697, 829, 1011)]
CHORDS = [
    ("EURK", EURK),
    ("MIN", [0, 300, 700, 1200, 1500, 1900]),
    ("MIN7", [0, 300, 700, 1000, 1200, 1500]),
    ("MIN9", [0, 300, 700, 1000, 1400, 1900]),
    ("MIN11", [0, 300, 700, 1000, 1400, 1700]),
    ("MAJ", [0, 400, 700, 1200, 1600, 1900]),
    ("MAJ7", [0, 400, 700, 1100, 1200, 1600]),
    ("DOM7", [0, 400, 700, 1000, 1200, 1600]),
    ("SUS2", [0, 200, 700, 1200, 1400, 1900]),
    ("SUS4", [0, 500, 700, 1200, 1700, 1900]),
    ("5TH", [0, 700, 1200, 1900, 2400, 3100]),
    ("DIM", [0, 300, 600, 900, 1200, 1500]),
    ("OCT", [0, 0, 1200, 1200, 2400, 2400]),
]


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    out = []
    w = out.append
    w("/* SPDX-License-Identifier: GPL-3.0-or-later */")
    w("/* Generated by tools/gen_tables.py: do not edit. */")
    w("#ifndef RA_TABLES_H\n#define RA_TABLES_H\n\n#include <stdint.h>\n")
    w("#define RA_CHORDS %d\n#define RA_NOTES 6\n" % len(CHORDS))
    w("/* CHD: six notes a chord, cents above the root. */")
    w("static const int16_t ra_chord_cents[RA_CHORDS][RA_NOTES] = {")
    for name, c in CHORDS:
        w("    { " + ", ".join(str(x) for x in c) + " },   /* %s */" % name)
    w("};\n")
    w("#endif")
    with open(os.path.join(here, "..", "src", "ra_tables.h"), "w") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
