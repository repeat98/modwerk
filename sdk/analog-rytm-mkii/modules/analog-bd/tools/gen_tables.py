#!/usr/bin/env python3
"""Analog BD's tables for the Rytm: the Octatrack module's own models at 48 kHz.

The 808 and 909 models, their fits and every coefficient are repeat98's, from
sdk/octabam/modules/analog-bassdrum (dsp808.py, dsp909.py, fit909.json; 0.1.7). This
script imports them, sets their sample rate to the Rytm's 48 kHz and writes the
tables and constants as Q31 words for src/tables.h. Nothing here is fitted anew.

    python3 tools/gen_tables.py > src/tables.h
"""
import math
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
OT = HERE.parents[3] / 'octabam' / 'modules' / 'analog-bassdrum'
sys.path.insert(0, str(OT))
import dsp909  # noqa: E402
import dsp808  # noqa: E402

RATE = 48000


def set_rate():
    """Every rate-dependent value of the two models, at RATE.

    The 909 (0.1.7) steps its control every 16 samples, as the Octatrack's block: the click
    16 samples after the trig, the release 32 later, the hold's end at block NHOLDB. The
    Rytm keeps those sample counts at 48 kHz (0.33 and 1.0 ms instead of 0.36 and 1.09), so
    the release time t_r is set to its 32 samples here, and the hold's end is the 16-sample
    block nearest the fit's t_h. dsp909.Voice at this rate, run 16 samples a call, is then
    the engine's reference sample for sample (tools/compare.py)."""
    dsp909.RATE = dsp808.RATE = RATE
    dsp909.NOISE_RMS = dsp909._white_rms_through_filters()
    dsp909.B['t_r'] = 32 / RATE
    dsp909.NHOLDB = round(dsp909.B['t_h'] * RATE / 16)
    dsp909.NIDLE = dsp909.NHOLDB + 1      # a voice may rest a block after the hold, as upstream


def q31(x):
    v = round(x * 2 ** 31)
    assert -2 ** 31 <= v < 2 ** 31 or x == 1.0, x
    return max(-2 ** 31, min(2 ** 31 - 1, v))


def table(name, vals):
    words = [q31(v) for v in vals]
    rows = [', '.join(f'{w}' for w in words[i:i + 8]) for i in range(0, len(words), 8)]
    return f'static const int32_t {name}[{len(words)}] = {{\n    ' + ',\n    '.join(rows) + ',\n};\n'


def table16(name, vals, scale):
    words = [max(-32768, min(32767, round(v * scale))) for v in vals]
    rows = [', '.join(f'{w}' for w in words[i:i + 12]) for i in range(0, len(words), 12)]
    return f'static const int16_t {name}[{len(words)}] = {{\n    ' + ',\n    '.join(rows) + ',\n};\n'


def phase(i, bits):
    """Table entry i's phase u in [-1, 1): the engine's uint32 phase i << (32 - bits)."""
    w = (i << (32 - bits)) & 0xffffffff
    return (w - (1 << 32) if w >> 31 else w) / 2 ** 31


def shape808(u):
    """The 808 body's wave before GAIN: sine/2 plus its measured second harmonic (dsp808.Voice.block)."""
    x = min(1 - 2 ** -31, 1 - 2 * abs(u))
    s = [math.pi / 4, -(math.pi / 2) ** 3 / 12, (math.pi / 2) ** 5 / 240, -(math.pi / 2) ** 7 / 10080,
         (math.pi / 2) ** 9 / 725760]
    h = s[4]
    for cf in s[3::-1]:
        h = cf + h * x * x
    sn = h * x
    return sn + .03076 - .246062 * sn * sn


def const(name, x):
    return f'#define {name} {q31(x)}  /* {x:.9g} */\n'


def main():
    set_rate()
    t, c, lists, meta = dsp909.tables()
    t8 = dsp808.tables()
    out = ['/* SPDX-License-Identifier: MIT */\n/* Generated by tools/gen_tables.py from the Octatrack Analog BD models\n'
           ' * (repeat98, MIT; 0.1.7) at 48 kHz. Q31 unless noted. Do not edit. */\n',
           '#ifndef AB_TABLES_H\n#define AB_TABLES_H\n#include <stdint.h>\n\n',
           '/* ---- 909 ---- */\n']
    t['T_VB'] = [min((i / 128) ** 2, 1 - 2 ** -31) for i in range(128)]   # the body's level, (ACNT/128)^2
    # The rest (render909) needs the VCA's stall below MREST: in Q31 m stops where m dkd
    # truncates to 0, under 2^31 / dkd, which is below 2^15 while every dkd is above 2^16.
    assert min(q31(v) for v in t['T_DKD']) > 2 ** 16, 'a stalled 909 VCA could stay above MREST'
    for k in ('T_INCB', 'T_AP', 'T_GT', 'T_GD', 'T_DKP', 'T_DKD', 'T_THS', 'T_VB', 'T_VA', 'T_ATP'):
        out.append(table(k, t[k]))
    for k in ('KTFB', 'KTFB0', 'KA_INC', 'K_BODY', 'U0', 'KEBASE', 'KA', 'DKDROOP', 'KTH',
              'KL0', 'KLE', 'KLM', 'KKF', 'KPBASE', 'KGS', 'KFDR', 'KPR', 'AHP', 'KA1', 'KB1',
              'KB2', 'KN0X', 'KN1Q', 'K2B', 'K3B', 'ANH', 'KL1', 'KL2', 'KSAT', 'KB', 'KM'):
        out.append(const(k, c[k]))
    # The noise high-pass's input runs at half scale here (Q31 cannot hold w - prev, up to 2).
    out.append(const('BNH2', 2 * c['BNH']))
    out.append(const('KMS2', c['KMS'] / 2))
    assert c['DCLK'] == 16 and c['NREL'] == 48 and c['NHOLD'] - 16 * dsp909.NHOLDB in range(-15, 16)
    out.append(f'#define DCLK {c["DCLK"]}  /* samples: the click and the noise */\n'
               f'#define NREL {c["NREL"]}  /* samples: the phase released */\n'
               f'#define NHOLD {16 * dsp909.NHOLDB}  /* samples: the hold ends, DECAY takes over */\n'
               f'#define NIDLE {16 * dsp909.NIDLE}  /* samples: a hit this old with m below MREST rests */\n'
               f'#define CLK_N {dsp909.CLK_N}  /* the click table\'s rows */\n')
    out.append(f'#define LCG_M {dsp909.LCG_M}u\n#define LCG_C {dsp909.LCG_C}u\n#define SEED {dsp909.SEED}u\n')
    # 16 steps of the LCG at once (a half block of a silent noise): x -> x * LCG_M16 + LCG_C16
    a, k = 1, 0
    for _ in range(16):
        a, k = a * dsp909.LCG_M % 2 ** 24, (k * dsp909.LCG_M + dsp909.LCG_C) % 2 ** 24
    out.append(f'#define LCG_M16 {a}u\n#define LCG_C16 {k}u\n')
    # The body: the recorded cycle without its fundamental and the fundamental, interleaved
    # (CTD[k], CF[k]) for k = 0..128, phase u = -1 + 2k/128; the last pair repeats the first.
    body = [v for pair in zip(lists['CTD'], lists['CF']) for v in pair]
    assert len(body) == 2 * 129
    out.append(table('BODY909', body))
    # The click: the pulse's two discharges through its filters, less their slow modes
    # (which the voice keeps as two decaying words), one row a sample, interleaved.
    out.append(table('CCLK', lists['CCLK'][:2 * dsp909.CLK_N]))
    # The desk at SAT 0 (the Rytm has no SAT knob): drive, make-up; DC-coupled (k_hp 0).
    # LOW and HIGH weight their bands (0.1.7): the low band's weight halved is T_GLH, the
    # high band's 2 T_GLH (the high band runs at half scale), both held under 1.
    out.append(const('D_TIN32', 32 * t['T_TIN'][0]))
    out.append(const('D_PAD', t['T_PAD'][0]))
    out.append(table('T_GL2', [min(v, (1 - 2 ** -23) / 2) for v in t['T_GLH']]))
    out.append(table('T_GH', [min(2 * v, 1 - 2 ** -23) for v in t['T_GLH']]))
    out.append(f'#define OUT909_SHIFT 2  /* x {dsp909.OUTPUT_GAIN}, then the limit */\n')

    out.append('\n/* ---- 808 ---- */\n')
    for k in ('B_INC', 'B_DE', 'B_DP', 'B_BEND', 'B_GAIN', 'B_TONE', 'B_VEL', 'B_ATK'):
        out.append(table(k, t8[k]))
    con = dict(PK=2 * math.sin(math.pi * 129.10747 / RATE), PD=-math.expm1(-1 / (RATE * .00203264)),
               DD=-math.expm1(-1 / (RATE * .00301295)), PC0=3.27303983 / 4, PS0=-1.57554231 / 4,
               DC0=-1.09270470 / 4, U8=(-1.3892912 - math.pi / 2) / math.pi,
               S1=math.pi / 4, S3=-(math.pi / 2) ** 3 / 12, S5=(math.pi / 2) ** 5 / 240,
               S7=-(math.pi / 2) ** 7 / 10080, S9=(math.pi / 2) ** 9 / 725760,
               H0=.03076, H2=-.246062, TRIM808=dsp808.OUTPUT_TRIM)
    for k, v in con.items():
        out.append(const(k, v))
    out.append(f'#define RETIRE808 {round(4096 * RATE / 44100)}  /* the trigger path\'s life, samples */\n')

    # The 808's wave, a pure function of phase sampled for linear interpolation (the
    # engine's mw_wave()). The polynomial is the model's own; error about -76 dB. The desk's curve
    # is worked out (ab_desk.s).
    out.append('\n/* ---- shapes ---- */\n')
    out.append('#define W_BITS 10  /* 1024 points a period, one more for the wrap */\n')
    out.append('#define W808_SHIFT 16  /* entries are the shape x 2^15 */\n')
    out.append(table16('W808', [shape808(phase(i, 10)) for i in range(1025)], 2 ** 15))
    out.append('\n#endif\n')
    sys.stdout.write(''.join(out))


if __name__ == '__main__':
    main()
