#!/usr/bin/env python3
"""Writes src/filters_tables.h: the Filters module's coefficient tables. Run from the module folder."""
import math
FS = 48000.0
TB = 32 / 48000.0                 # one render block
def q31(v): return max(-2**31, min(2**31 - 1, int(round(v * 2**31))))
def q30(v): return int(round(v * 2**30))
def q27(v): return int(round(v * 2**27))
fc = [20.0 * 2 ** (i * 10.0 / 127) for i in range(129)]
fg = [int(round(math.tan(math.pi * min(f, 20000.0) / FS) * 65536)) for f in fc]   # TPT g = tan(pi fc / fs), Q16
qres = [q30(1.414 * (0.045 / 1.414) ** (i / 127.0)) for i in range(128)]          # damping: Butterworth .. near self-oscillation
qdj = [q30(1.414 * (0.38 / 1.414) ** (i / 127.0)) for i in range(128)]            # DJ: a gentler peak
att = [q31(1 - math.exp(-TB / (0.0003 * 2 ** (i * 11.7 / 127)))) for i in range(128)]   # 0.3 ms .. 1 s
rel = [q31(1 - math.exp(-TB / (0.005 * 2 ** (i * 9.2 / 127)))) for i in range(128)]     # 5 ms .. 3 s
sens = [q27(2 ** (i / 32.0)) for i in range(128)]                                   # x1 at 0 (the stock default) .. x15.7
def arr(name, ctype, v):
    s = 'static const %s %s[%d] = {\n' % (ctype, name, len(v))
    for i in range(0, len(v), 8): s += '    ' + ', '.join('%d' % x for x in v[i:i + 8]) + ',\n'
    return s + '};\n'
out = '/* Generated by tools/gen_tables.py; do not edit. */\n'
out += '/* g = tan(pi fc / 48 kHz), Q16, fc = 20 Hz * 2^(i * 10 / 127), capped at 20 kHz */\n' + arr('ft_g', 's32', fg)
out += '/* Damping k = 1/Q, Q30: RESO 0 (1.414, no peak) .. 127 (0.045) */\n' + arr('ft_q', 's32', qres)
out += '/* DJ damping, Q30: 1.414 .. 0.38 */\n' + arr('ft_qdj', 's32', qdj)
out += '/* Follower attack (ATK) and release (DEC), per 32-frame block, Q31 */\n' + arr('ft_att', 's32', att) + arr('ft_rel', 's32', rel)
out += '/* Follower sensitivity (SUS), Q27: 2^(SUS / 32) */\n' + arr('ft_sens', 's32', sens)
open('src/filters_tables.h', 'w').write(out)
